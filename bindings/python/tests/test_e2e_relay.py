# 6. Context lifecycle with relay
# ---------------------------------------------------------------------------


class TestContextLifecycleWithRelay:
    """Full create -> join -> send -> leave -> close cycle."""

    def test_full_lifecycle(self, scp: SCP) -> None:
        alice_did = _create_identity(scp)
        bob_did = _create_identity(scp)

        handle = scp._native.context_create(
            alice_did,
            {
                "ceiling": [
                    "messages:read",
                    "messages:write",
                    "member:invite",
                    "role:assign",
                    "context:close",
                ],
                "memory_scope": "ephemeral",
                "governance": "single_admin",
            },
        )

        # Join
        scp._native.context_join(handle, bob_did)
        assert scp._native.context_member_count(handle) == 2

        scp._native.context_seed_peer_pseudonym(handle, bob_did, bytes([0x42] * 32))

        # Send
        scp._native.context_send(handle, alice_did, b"lifecycle test message")

        # Bob leaves
        scp._native.context_leave(handle, bob_did)
        assert scp._native.context_member_count(handle) == 1

        # Alice closes
        scp._native.context_close(handle, alice_did)

    def test_send_on_closed_context_fails(self, scp: SCP) -> None:
        alice_did = _create_identity(scp)

        handle = scp._native.context_create(
            alice_did,
            {
                "ceiling": ["messages:read", "messages:write", "context:close"],
                "memory_scope": "ephemeral",
                "governance": "single_admin",
            },
        )

        scp._native.context_close(handle, alice_did)

        # Send on closed context must fail
        with pytest.raises(Exception):
            scp._native.context_send(handle, alice_did, b"should fail")


