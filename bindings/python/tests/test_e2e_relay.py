from scp_sdk import SCP

# ---------------------------------------------------------------------------
# Session-scoped SCP + relay fixture
# ---------------------------------------------------------------------------
#
# ``configure_relay_transport`` is OnceLock-bound — first call per bridge
# instance wins — so this module shares one :class:`SCP` across every
# test. The function-scoped ``scp`` fixture aliases it so tests follow
# the canonical ``scp`` parameter name without re-initialising the
# relay wiring for every test.


@pytest.fixture(scope="session")
def session_scp() -> SCP:
    """Session-wide :class:`scp_sdk.SCP` that owns the relay wiring.

    Phase 4 PR 4 (#1549) removed the process-global default bridge
    instance; every caller now owns its own ``SCP()``. Handle-affinity
    is wired end-to-end for caller-owned instances, so a fresh bridge
    for the session is the canonical shape.

    Storage-required model (ADR-049 / spec §17.6): the ``relay`` fixture
    wires the production relay path (``configure_relay_transport``), which
    deliberately does NOT default storage — without a storage backend the
    supervisor build fails closed and every ``context_create`` raises
    SCP-CTX-2001. We construct via ``SCP.with_storage({"type":
    "in_memory"})`` (the sanctioned test affordance under
    ``testing``) so a storage backend is present before
    ``configure_relay_transport`` derives the supervisor's ``mls_storage``
    view from it.
    """
    wrapper = SCP.__new__(SCP)
    wrapper._native = _scp_core.SCP.with_storage({"type": "in_memory"})
    yield wrapper


@pytest.fixture(scope="session", autouse=True)
def relay(session_scp: SCP):
    """Start an in-memory relay for the entire test session.

    Initializes the ContextManager with a RelayTransportProvider so
    context_send publishes through the relay.  A second connection
    (transport_connect) is established for relay-based discovery.
    """
    native = session_scp._native
    handle = native.relay_start_in_memory()

    # Create a bootstrap identity for the MLS credential DID.
    bootstrap = native.identity_create("in_memory")

    # Wire the ContextManager to use a real relay transport provider.
    # Must be called BEFORE any context_create (OnceLock — first call wins).
    native.configure_relay_transport(handle.relay_url, bootstrap.did)

    # Second connection for relay-based context discovery.
    native.transport_connect(handle.relay_url)

    yield handle
    if not handle.is_shutdown:
        handle.shutdown()


@pytest.fixture
def scp(session_scp: SCP) -> SCP:
    """Per-test alias for the session-scoped bridge (see module docstring)."""
    return session_scp


