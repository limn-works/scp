# 2. Two-party encrypted send through real relay
# ---------------------------------------------------------------------------


class TestTwoPartyEncryptedMessaging:
    """Alice and Bob exchange messages through real MLS + relay."""

    def test_alice_creates_context_bob_joins_alice_sends(self, scp: SCP) -> None:
        alice_did = _create_identity(scp)
        bob_did = _create_identity(scp)

        assert alice_did.startswith("did:dht:")
        assert bob_did.startswith("did:dht:")
        assert alice_did != bob_did

        # Alice creates an encrypted context
        handle = scp._native.context_create(
            alice_did,
            {
                "ceiling": ["messages:read", "messages:write", "member:invite", "role:assign"],
                "memory_scope": "ephemeral",
                "governance": "single_admin",
            },
        )
        assert handle.context_id
        assert handle.state == "active"

        # Bob joins
        scp._native.context_join(handle, bob_did)
        assert scp._native.context_member_count(handle) == 2
        assert scp._native.context_is_member(handle, bob_did)
        assert scp._native.context_is_member(handle, alice_did)

        members = scp._native.context_member_dids(handle)
        assert alice_did in members
        assert bob_did in members

        scp._native.context_seed_peer_pseudonym(handle, bob_did, bytes([0x42] * 32))

        # Alice sends -- exercises the full pipeline:
        # inner envelope creation (Ed25519 signing) -> MLS encryption ->
        # sender key encryption -> outer envelope -> relay publish.
        scp._native.context_send(handle, alice_did, b"hello from Alice to Bob")

    def test_bob_sends_reply(self, scp: SCP) -> None:
        alice_did = _create_identity(scp)
        bob_did = _create_identity(scp)

        handle = scp._native.context_create(
            alice_did,
            {
                "ceiling": ["messages:read", "messages:write", "member:invite", "role:assign"],
                "memory_scope": "ephemeral",
                "governance": "single_admin",
            },
        )

        scp._native.context_join(handle, bob_did)

        scp._native.context_seed_peer_pseudonym(handle, bob_did, bytes([0x42] * 32))
        scp._native.context_seed_peer_pseudonym(handle, alice_did, bytes([0x41] * 32))

        # Alice sends
        scp._native.context_send(handle, alice_did, b"message from Alice")

        # Bob replies
        scp._native.context_send(handle, bob_did, b"reply from Bob")


