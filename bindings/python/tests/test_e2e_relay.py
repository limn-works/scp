class TestThreePartyEncryptedMessaging:
    """Alice, Bob, and Carol all exchange messages in one context."""

    def test_three_party_send(self, scp: SCP) -> None:
        alice_did = _create_identity(scp)
        bob_did = _create_identity(scp)
        carol_did = _create_identity(scp)

        handle = scp._native.context_create(
            alice_did,
            {
                "ceiling": ["messages:read", "messages:write", "member:invite", "role:assign"],
                "memory_scope": "ephemeral",
                "governance": "single_admin",
            },
        )

        scp._native.context_join(handle, bob_did)
        scp._native.context_join(handle, carol_did)

        assert scp._native.context_member_count(handle) == 3

        scp._native.context_seed_peer_pseudonym(handle, bob_did, bytes([0x42] * 32))
        scp._native.context_seed_peer_pseudonym(handle, carol_did, bytes([0x43] * 32))
