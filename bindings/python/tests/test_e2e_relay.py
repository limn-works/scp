"""E2E encrypted messaging tests through a real in-process relay.

These tests exercise the FULL protocol stack:
- Real did:dht identity creation (ADR-003)
- Real MLS group encryption (ADR-001)
- Real sender key signing (ADR-007)
- Real inner/outer envelope construction (ADR-002)
- Real WebSocket relay transport (ADR-004, ADR-005)

The relay is started in-process via ``relay_start_in_memory()`` on a
shared :class:`scp_sdk.SCP` fixture. ``configure_relay_transport(relay_url,
local_did)`` initializes the ContextManager with a
``RelayTransportProvider`` so ``context_send`` publishes encrypted
payloads through the relay. ``transport_connect()`` establishes a
second connection for relay-based context discovery.

NOTE: The Python bridge's ``context_receive()`` uses a local channel
(``drain_and_deliver``) that delivers events generated by the local
ContextManager -- it does NOT subscribe to the relay.  Full relay-backed
receive is verified in the TypeScript E2E tests via ``contextSubscribe``.

Prerequisites:
    ``maturin develop --release --features testing``

Run:
    PYTHONPATH=bindings/python python3.12 -m pytest bindings/python/tests/test_e2e_relay.py -v
"""

from __future__ import annotations

