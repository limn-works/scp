    ///   - ttlSeconds: Time-to-live for the session in seconds, or `nil` for
    ///     a session that persists for the lifetime of the context (spec section 6.2.1).
    ///   - sessionCreateFn: Bridge function override for testing.
    /// - Returns: A ``OutletSessionResult`` containing the session ID.
    /// - Throws: ``ScpError/Outlet(msg:code:)`` if session creation fails.
    ///   ``ScpError/Context(msg:code:)`` if the context is not active.
    ///
    /// ## Provenance
    ///
    /// - Spec section 6.2.1 (Stateful Outlet Sessions)
