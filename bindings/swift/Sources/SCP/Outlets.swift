    /// Invokes an outlet registered in a different context (cross-context).
    ///
    /// Delegates to the UniFFI ``outletInvokeCrossContext`` bridge function.
    /// Requires bidirectional consent: the source context must allow outbound
    /// outlet calls and the target context must allow inbound outlet calls.
    /// Chain depth is enforced (max 3 hops per spec section 6.2).
    ///
    /// - Parameters:
    ///   - outlet: The outlet ID to invoke in the target context.
    ///   - input: The outlet input as serialized JSON data.
    ///   - identity: The ``Identity`` of the invoking agent.
    ///   - targetContext: The ``Context`` containing the target outlet.
    ///   - chainDepth: Current chain depth (0 for direct invocation).
    ///   - invokeCrossContextFn: Bridge function override for testing.
    /// - Returns: A ``OutletInvocationResult`` containing the outlet's output
    ///   and provenance metadata.
    /// - Throws: ``ScpError/Outlet(msg:code:)`` if the outlet is not found,
    ///   chain depth exceeds the limit, or consent is denied.
    ///   ``ScpError/Context(msg:code:)`` if either context is not active.
    ///
    /// ## Provenance
    ///
    /// - Spec section 6.2 (Cross-Context Outlet Interfaces)
    /// - Story #322
    func invokeOutletCrossContext(
        _ outlet: String,
        input: Data,
        identity: Identity,
        targetContext: Context,
        ucanToken: String,
        chainDepth: UInt8 = 0,
        proofTokens: [String]? = nil,
        invokerDid: String? = nil
    ) async throws -> OutletInvocationResult {
        guard state == .active else {
            throw ScpError.Context(
                msg: "Source context is not active",
                code: "SCP-CTX-2001"
            )
        }
        guard let inputJson = String(data: input, encoding: .utf8) else {
            throw ScpError.Outlet(
                msg: "Outlet input is not valid UTF-8",
                code: "SCP-OUTLET-6001"
            )
        }
        let targetHandle = targetContext.handle
        let outputJson = try await scp.outletInvokeCrossContext(
            sourceHandle: handle,
            targetHandle: targetHandle,
            outletId: outlet,
            inputJson: inputJson,
            identity: identity,
            ucanToken: ucanToken,
            chainDepth: chainDepth,
            proofTokens: proofTokens
        )
        return OutletInvocationResult(
            output: Data(outputJson.utf8),
            invokerDid: invokerDid ?? identity.did(),
            contextId: contextId,
            timestamp: UInt64(Date().timeIntervalSince1970 * 1000)
        )
    }

    /// Runs the §6.2.4 atomic cross-context outlet-invocation saga.
    ///
    /// Delegates to the UniFFI ``outletInvokeCrossContextSaga`` bridge function.
    /// Unlike ``invokeOutletCrossContext(_:input:identity:targetContext:ucanToken:chainDepth:proofTokens:invokerDid:)``
    /// (a single synchronous cross-context call), this drives the durable
    /// two-phase saga to a terminal: the call blocks until the saga either
    /// commits — resolving to a ``SagaResult`` carrying the supervisor-minted
    /// ``SagaResult/sagaId`` plus the target's signed receipt and captured
    /// output bytes — or reaches a typed terminal, surfaced directly as one of
    /// the generated ``ScpError`` saga cases:
    ///
    /// - ``ScpError/SagaAborted(msg:code:retryAfterMs:)`` — a Prepare-phase
    ///   abort: a PERMANENT rejection OR a RETRYABLE transient (rate limit /
    ///   participant actor unavailable), distinguished by the `SCP-SAGA-*`
    ///   code. `retryAfterMs` is the limiter's computed back-off, or `nil`
    ///   (never `0`) when no precise back-off instant exists.
    /// - ``ScpError/SagaNeedsRepair(msg:code:sagaId:)`` — Commit retries
    ///   exhausted (a possible divergence); carries the durable `sagaId`
    ///   operator-repair handle.
    /// - ``ScpError/SagaBusy(msg:code:contendedContext:)`` — the participant
    ///   context set overlapped an in-flight saga; carries the contended
    ///   context id (retry with back-off).
    ///
    /// The `chainDepth` (`UInt8`) and `timestampMs` (`UInt64`) parameters
    /// cannot encode an out-of-range or negative value, so no manual range
    /// validation is performed — Swift's type system enforces the bridge's
    /// `u8` / `u64` boundaries by construction.
    ///
    /// - Parameters:
    ///   - targetContext: The ``Context`` hosting the target outlet.
    ///   - callerDid: The DID of the invoking principal (bound to the
    ///     authenticated FFI identity by the bridge).
    ///   - outletRegistrationId: The target outlet's registration id.
    ///   - input: The outlet input as serialized JSON data.
    ///   - assertedNonceHex: The caller-asserted freshness nonce, as 32 hex
    ///     characters (16 bytes); the bridge rejects other lengths with a
    ///     `Validation` error.
    ///   - timestampMs: The caller-asserted freshness timestamp
    ///     (milliseconds since epoch).
    ///   - chainDepth: The caller-asserted inbound chain depth (0 for a
    ///     direct invocation).
    ///   - ucanProofId: Optional UCAN proof id authorizing the invocation.
    /// - Returns: A ``SagaResult`` on a committed terminal — a faithful
    ///   pass-through of the bridge result (`receipt` / `output` are surfaced
    ///   exactly as returned, `nil` when absent, never synthesized).
    /// - Throws: ``ScpError/SagaAborted(msg:code:retryAfterMs:)``,
    ///   ``ScpError/SagaNeedsRepair(msg:code:sagaId:)``, or
    ///   ``ScpError/SagaBusy(msg:code:contendedContext:)`` on a non-committed
    ///   terminal; ``ScpError/Context(msg:code:)`` (`SCP-CTX-2001`) if the
    ///   source context is not active; ``ScpError/Outlet(msg:code:)``
    ///   (`SCP-OUTLET-6001`) if the input is not valid UTF-8;
    ///   ``ScpError/Outlet(msg:code:)`` (`SCP-OUTLET-6002`, propagated from the
    ///   bridge) if `input` is valid UTF-8 but not valid JSON;
    ///   ``ScpError/Validation(msg:code:)`` (propagated from the bridge) if
    ///   `assertedNonceHex` is not 16-byte hex, or `callerDid` /
    ///   `outletRegistrationId` is malformed; ``ScpError/Permission(msg:code:)``
    ///   (`SCP-PERM-3030`, propagated from the bridge) if `targetContext` is a
    ///   foreign / cross-instance handle.
    ///
    /// ## Provenance
    ///
    /// - Spec section 6.2.4 (Cross-Context Outlet Invocation Saga)
    /// - ADR-049 §3a (per-participant-context-set saga gating)
    func invokeOutletCrossContextSaga(
        targetContext: Context,
        callerDid: String,
        outletRegistrationId: String,
        input: Data,
        assertedNonceHex: String,
        timestampMs: UInt64,
        chainDepth: UInt8,
        ucanProofId: String? = nil
    ) async throws -> SagaResult {
        guard state == .active else {
            throw ScpError.Context(
                msg: "Source context is not active",
                code: "SCP-CTX-2001"
            )
        }
        guard let inputJson = String(data: input, encoding: .utf8) else {
            throw ScpError.Outlet(
                msg: "Outlet input is not valid UTF-8",
                code: "SCP-OUTLET-6001"
            )
        }
        let targetHandle = targetContext.handle
        return try await scp.outletInvokeCrossContextSaga(
            sourceHandle: handle,
            targetHandle: targetHandle,
            callerDid: callerDid,
            outletRegistrationId: outletRegistrationId,
            inputJson: inputJson,
            assertedNonceHex: assertedNonceHex,
            timestampMs: timestampMs,
            chainDepth: chainDepth,
            ucanProofId: ucanProofId
        )
    }

    /// Creates a stateful outlet session for repeated invocations.
    ///
    /// Delegates to the UniFFI ``outletSessionCreate`` bridge function.
