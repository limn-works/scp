// instance stored on the owning ``Context`` actor (see ``Context/scp``),
// which matches the Kotlin SDK shape.

// MARK: - Context Outlet Extensions

/// Outlet invocation and management extensions for ``Context``.
public extension Context {
    /// Invokes a registered outlet in this context.
    ///
    /// Delegates to the UniFFI ``outletInvoke`` bridge function. The input Data
    /// is converted to a UTF-8 JSON string for the bridge call, and the output
    /// JSON string is wrapped in a ``OutletInvocationResult`` with provenance.
    ///
    /// - Parameters:
    ///   - outlet: The name of the outlet to invoke.
    ///   - input: The outlet input as serialized JSON data.
    ///   - identity: The ``Identity`` of the invoking agent.
    ///   - invokeFn: Bridge function override for testing.
    /// - Returns: A ``OutletInvocationResult`` containing the outlet's output and
    ///   provenance metadata.
    /// - Throws: ``ScpError/Outlet(msg:code:)`` if the outlet is not found,
    ///   the input fails schema validation, or the invocation is unauthorized.
    ///   ``ScpError/Context(msg:code:)`` if the context is not active.
    ///
    /// ## Provenance
    ///
    /// - ADR-011 (Event Log) in `.docs/adrs/phase-2.md`
    /// - ADR-026 (Swift SDK) in `.docs/adrs/phase-5.md`
    /// - Story SCP-221
    func invokeOutlet(
        _ outlet: String,
        input: Data,
        identity: Identity,
        ucanToken: String? = nil,
        proofTokens: [String]? = nil,
        spendingUcan: String? = nil,
        invokerDid: String? = nil
    ) async throws -> OutletInvocationResult {
        guard state == .active else {
            throw ScpError.Context(
                msg: "Context is not active",
                code: "SCP-CTX-2001"
            )
        }
        guard let inputJson = String(data: input, encoding: .utf8) else {
            throw ScpError.Outlet(
                msg: "Outlet input is not valid UTF-8",
                code: "SCP-OUTLET-6001"
            )
        }
        let outputJson = try await scp.outletInvoke(
            handle: handle,
            outletId: outlet,
            inputJson: inputJson,
            identity: identity,
            ucanToken: ucanToken,
            proofTokens: proofTokens,
            spendingUcanJwt: spendingUcan
        )
        return OutletInvocationResult(
            output: Data(outputJson.utf8),
            invokerDid: invokerDid ?? identity.did(),
            contextId: contextId,
            timestamp: UInt64(Date().timeIntervalSince1970 * 1000)
        )
    }

