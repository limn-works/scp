// MARK: - OutletInvocationResult

/// The result of invoking an outlet within an SCP context.
///
/// Contains the outlet's output payload and provenance metadata recording which
/// agent invoked the outlet, in which context, and when.
///
/// This type is a pure Swift convenience type not generated by UniFFI.
///
/// See `.docs/sketch.md` section 4 "Outlets (within a context)".
public nonisolated struct OutletInvocationResult: Sendable {
    /// The serialized output from the outlet invocation (JSON).
    public let output: Data

    /// The DID of the agent that invoked the outlet.
    public let invokerDid: String

    /// The context ID in which the outlet was invoked.
    public let contextId: String

    /// Unix timestamp (milliseconds since epoch) of the invocation.
    public let timestamp: UInt64

    /// Memberwise initializer.
    public init(
        output: Data,
        invokerDid: String,
        contextId: String,
        timestamp: UInt64
    ) {
        self.output = output
        self.invokerDid = invokerDid
        self.contextId = contextId
        self.timestamp = timestamp
    }
}

// MARK: - OutletSessionResult

/// The result of creating a stateful outlet session.
///
/// Contains the session ID and metadata needed to invoke the outlet within
/// the session.
///
/// See spec section 6.2.1 (Stateful Outlet Sessions).
public nonisolated struct OutletSessionResult: Sendable {
    /// The unique session ID (UUID).
    public let sessionId: String

    /// Memberwise initializer.
    public init(sessionId: String) {
        self.sessionId = sessionId
    }
}

// Phase 4 PR 4 (ADR-048 demolition, #1549): the `OutletBridge` namespace —
// injectable closures whose defaults called `Scp.defaultInstance()` — has
