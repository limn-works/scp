import Foundation

// TrustInput is defined by UniFFI in ScpBindings.swift as a struct with:
//   subjectDid, contextId, verifiedAttestationCount, participationCount,
//   triggeredConsequences, evaluatedAt
//
// TrustScoreResult is defined by UniFFI in ScpBindings.swift as a struct with:
//   messageCount, governanceCount, compositeScore
//
// AttestationVerificationResult is defined by UniFFI in ScpBindings.swift as a struct with:
//   valid, chainDepth, errorMessage
//
// ChallengeResult is defined by UniFFI in ScpBindings.swift as a struct with:
//   challengeId, challengeJson
//
// TrustEvaluation and BehavioralRecord are pure Swift convenience types
// that compose trust data from multiple sources.

// MARK: - TrustEvaluation

/// The result of evaluating trust for a subject within a context.
///
/// Aggregates verifiable facts from the SCP four-layer trust model.
/// This type is a pure Swift convenience type not generated by UniFFI.
///
/// ## Provenance
///
/// - ADR-017 (Trust Model) in `.docs/adrs/phase-4.md`
/// - `.docs/sketch.md` section 5 "Trust & Capabilities"
/// - Story SCP-221, #331
public nonisolated struct TrustEvaluation: Sendable {
    // MARK: - Layer 1: Protocol Enforcement

    /// Whether all UCAN tokens in the subject's presentation are valid.
    public let tokensValid: Bool

    /// Whether all Ed25519 signatures verified successfully.
    public let signaturesValid: Bool

    /// Whether the subject's capabilities are within the context's ceiling.
    public let withinCeiling: Bool

    /// Whether none of the presented tokens have been revoked.
    public let notRevoked: Bool

    // MARK: - Layer 2: Behavioral Validation

    /// The behavioral record for the subject, if event log data is available.
    public let behavioralRecord: BehavioralRecord?

    // MARK: - Layer 3: Attestation

    /// The number of verified attestations for the subject.
    public let verifiedAttestationCount: Int

    /// The number of verified challenge-response results.
    public let challengeResultCount: Int

    // MARK: - Layer 4: Consequence

    /// The number of consequence rules declared for the context.
    public let consequenceRuleCount: Int

    /// Memberwise initializer.
    public init(
        tokensValid: Bool,
        signaturesValid: Bool,
        withinCeiling: Bool,
        notRevoked: Bool,
        behavioralRecord: BehavioralRecord?,
        verifiedAttestationCount: Int,
        challengeResultCount: Int,
        consequenceRuleCount: Int
    ) {
        self.tokensValid = tokensValid
        self.signaturesValid = signaturesValid
        self.withinCeiling = withinCeiling
        self.notRevoked = notRevoked
        self.behavioralRecord = behavioralRecord
        self.verifiedAttestationCount = verifiedAttestationCount
        self.challengeResultCount = challengeResultCount
        self.consequenceRuleCount = consequenceRuleCount
    }

    /// Creates a ``TrustEvaluation`` from a UniFFI ``TrustInput`` record.
    ///
    /// Maps the flat UniFFI record to the four-layer trust model structure.
    /// Protocol enforcement fields (Layer 1) default to `true` since the
    /// Rust engine enforces these mechanically.
    public init(from input: TrustInput) {
        tokensValid = true
        signaturesValid = true
        withinCeiling = true
        notRevoked = true
        behavioralRecord = BehavioralRecord(
            contextsParticipated: Int(input.participationCount),
            totalDurationSecs: 0,
            governanceActionsAgainst: Int(input.triggeredConsequences),
            toolInvocations: 0,
            roleTransitions: 0
        )
        verifiedAttestationCount = Int(input.verifiedAttestationCount)
        challengeResultCount = 0
        consequenceRuleCount = Int(input.triggeredConsequences)
    }

    /// Creates a ``TrustEvaluation`` from a UniFFI ``TrustScoreResult``.
    public init(from score: TrustScoreResult) {
        tokensValid = true
        signaturesValid = true
        withinCeiling = true
        notRevoked = true
        behavioralRecord = BehavioralRecord(
            contextsParticipated: 0,
            totalDurationSecs: 0,
            governanceActionsAgainst: Int(score.governanceCount),
            toolInvocations: 0,
            roleTransitions: 0
        )
        verifiedAttestationCount = 0
        challengeResultCount = 0
        consequenceRuleCount = 0
    }
}

// MARK: - BehavioralRecord

/// Verified behavioral facts for a subject DID, computed from a context's
/// event log.
///
/// See ADR-017 Layer 2 in `.docs/adrs/phase-4.md`.
public nonisolated struct BehavioralRecord: Sendable {
    /// Number of contexts the subject has participated in.
    public let contextsParticipated: Int

    /// Total duration of participation across all contexts (seconds).
    public let totalDurationSecs: UInt64

    /// Number of governance actions taken against the subject.
    public let governanceActionsAgainst: Int

    /// Number of tool invocations by the subject.
    public let toolInvocations: Int

    /// Number of role transitions for the subject.
    public let roleTransitions: Int

    /// Memberwise initializer.
    public init(
        contextsParticipated: Int,
        totalDurationSecs: UInt64,
        governanceActionsAgainst: Int,
        toolInvocations: Int,
        roleTransitions: Int
    ) {
        self.contextsParticipated = contextsParticipated
        self.totalDurationSecs = totalDurationSecs
        self.governanceActionsAgainst = governanceActionsAgainst
        self.toolInvocations = toolInvocations
        self.roleTransitions = roleTransitions
    }
}

// MARK: - AggregatedTrustInput

/// Aggregated trust input result.
///
/// Contains the JSON-decoded output of the trust aggregation pipeline.
/// Each field corresponds to one of the four trust layers.
///
/// ## Provenance
///
/// - ADR-017 acceptance criterion 9
/// - Spec section 7.3
public nonisolated struct AggregatedTrustInput {
    /// Verified attestations (Layer 3), as raw JSON-decoded objects.
    public let verifiedAttestations: [[String: Any]]

    /// Participation record (Layer 2), as a raw JSON-decoded object.
    public let participationRecord: [String: Any]

    /// Challenge-response results (Layer 3), as raw JSON-decoded objects.
    public let challengeResults: [[String: Any]]

    /// Consequence rules (Layer 4), as raw JSON-decoded objects.
    public let consequenceStructure: [[String: Any]]

    /// Threshold counts per attestation type: [met, required].
    public let thresholdCounts: [String: [Int]]
}

public extension SCP {
    /// Evaluates trust for a subject DID within a context.
    ///
    /// Routes through ``SCP/trustQueryScore`` to build a
    /// ``TrustEvaluation``.
    func evaluateTrust(subjectDid: String, contextId: String) throws -> TrustEvaluation {
        let score = try trustQueryScore(did: subjectDid, contextId: contextId)
        return TrustEvaluation(from: score)
    }

    /// Aggregates all trust engine layers into a single input for
    /// agent-level evaluation.
    ///
    /// Routes through ``SCP/aggregateTrustInput`` and parses the JSON
    /// result into a typed ``AggregatedTrustInput``.
    func aggregateTrust(
        contextId: String,
        subjectDid: String,
        eventsJson: String,
        merkleRootJson: String,
        consequenceRulesJson: String = "[]",
        thresholdRequirementsJson: String = "{}",
        attestorSetsJson: String = "{}",
        cachedAttestationsJson: String = "[]",
        challengeResultsJson: String = "[]"
    ) throws -> AggregatedTrustInput {
        let resultJson = try aggregateTrustInput(
            contextId: contextId,
            subjectDid: subjectDid,
            eventsJson: eventsJson,
            merkleRootJson: merkleRootJson,
            consequenceRulesJson: consequenceRulesJson,
            thresholdRequirementsJson: thresholdRequirementsJson,
            attestorSetsJson: attestorSetsJson,
            cachedAttestationsJson: cachedAttestationsJson,
            challengeResultsJson: challengeResultsJson
        )

        guard let data = resultJson.data(using: .utf8),
              let json = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
            throw ScpError.Validation(
                msg: "failed to parse aggregation result JSON",
                code: "SCP-VALID-7060"
            )
        }

        return AggregatedTrustInput(
            verifiedAttestations: json["verified_attestations"] as? [[String: Any]] ?? [],
            participationRecord: json["participation_record"] as? [String: Any] ?? [:],
            challengeResults: json["challenge_results"] as? [[String: Any]] ?? [],
            consequenceStructure: json["consequence_structure"] as? [[String: Any]] ?? [],
            thresholdCounts: json["threshold_counts"] as? [String: [Int]] ?? [:]
        )
    }
}

// MARK: - Participation Types

/// A verifiable participation fact type.
///
/// Participation facts represent quantifiable behavioral signals that can
/// be observed from a context's event log. They are inputs to the trust
/// model's behavioral validation layer (Layer 2).
///
/// ## Provenance
///
/// - ADR-017 Layer 2 (Behavioral Validation)
/// - Spec section 23.7 (Participation Requirements)
public enum ParticipationFact: String, Sendable, CaseIterable {
    /// Number of messages sent by the participant.
    case messagesSent = "messages_sent"

    /// Number of tools invoked by the participant.
    case toolsInvoked = "tools_invoked"

    /// Number of governance actions taken by the participant.
    case governanceActions = "governance_actions"

    /// Number of contexts the participant has joined.
    case contextsParticipated = "contexts_participated"

    /// Number of attestations the participant has verified.
    case attestationsVerified = "attestations_verified"
}

/// A minimum threshold for a specific participation fact.
public nonisolated struct ParticipationThreshold: Sendable {
    /// The participation fact to check.
    public let fact: ParticipationFact

    /// The minimum value required.
    public let minimum: UInt64

    /// Memberwise initializer.
    public init(fact: ParticipationFact, minimum: UInt64) {
        self.fact = fact
        self.minimum = minimum
    }
}

/// A participant's observed values for each participation fact.
public typealias ParticipationProfile = [ParticipationFact: UInt64]

/// A set of participation thresholds for admission gating.
public nonisolated struct RequireParticipation: Sendable {
    /// The thresholds to check.
    public let thresholds: [ParticipationThreshold]

    /// If `true`, **all** thresholds must be met (AND logic).
    public let requireAll: Bool

    /// Memberwise initializer.
    public init(thresholds: [ParticipationThreshold], requireAll: Bool = true) {
        self.thresholds = thresholds
        self.requireAll = requireAll
    }
}

// MARK: - Participation Verification

/// Verifies that a participation profile meets the required thresholds.
///
/// This is a pure Swift function with no bridge dependency.
///
/// - Parameters:
///   - requirement: The participation thresholds to check.
///   - profile: The observed participation values.
/// - Returns: `true` if the requirement is satisfied, `false` otherwise.
public func verifyParticipationRequirements(
    requirement: RequireParticipation,
    profile: ParticipationProfile
) -> Bool {
    if requirement.thresholds.isEmpty {
        return true
    }

    let results = requirement.thresholds.map { threshold -> Bool in
        let observed = profile[threshold.fact] ?? 0
        return observed >= threshold.minimum
    }

    return requirement.requireAll
        ? results.allSatisfy { $0 }
        : results.contains { $0 }
}
