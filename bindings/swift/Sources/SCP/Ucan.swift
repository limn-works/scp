// MARK: - UcanCapability

/// A single capability grant within a UCAN token.
///
/// Each capability specifies a resource URI and an action. Resource URIs
/// follow the SCP capability URI format: `scp:ctx:{context_id}/{capability}`.
/// Wildcards are supported: `scp:ctx:*/messages:write` matches any context.
///
/// This type is a pure Swift convenience type not generated by UniFFI.
///
/// See ADR-016 acceptance criterion 4.
public nonisolated struct UcanCapability: Sendable {
    /// Resource URI (e.g., `"scp:ctx:abc123/messages:write"`).
    public let resource: String

    /// Action (e.g., `"invoke"`, `"read"`, `"write"`).
    public let action: String

    /// Memberwise initializer.
    public init(resource: String, action: String) {
        self.resource = resource
        self.action = action
    }
}

// MARK: - UcanValidationResult

/// The result of validating a UCAN token.
///
/// Contains the validation outcome and, if valid, the extracted token.
/// This type is a pure Swift convenience type not generated by UniFFI.
public nonisolated struct UcanValidationResult: Sendable {
    /// Whether the token passed all validation checks.
    public let isValid: Bool

    /// The validated token, if validation succeeded. `nil` if validation failed.
    public let token: UcanToken?

    /// A human-readable reason if validation failed. `nil` if valid.
    public let failureReason: String?

    /// Memberwise initializer.
    public init(isValid: Bool, token: UcanToken?, failureReason: String?) {
        self.isValid = isValid
        self.token = token
        self.failureReason = failureReason
    }
}

// MARK: - UcanBridge

/// Namespace for UniFFI bridge function references used by UCAN operations.
/// Each typealias maps 1:1 to a UniFFI-generated async function. Closures are
/// injected for testability; defaults call through to ScpBindings.
///
/// See ADR-026 for the flat delegation pattern and ADR-016 for UCAN spec.
public enum UcanBridge {
    /// Validate a UCAN token. Maps to ``ucanValidate`` in ScpBindings.
    public typealias ValidateFn = @Sendable (
        _ handle: ContextHandle,
        _ token: String,
        _ capability: String,
        _ presentingAgentDid: String?,
        _ proofTokens: [String]?
    ) async throws -> Void

    /// Mint a UCAN token. Maps to ``ucanMint`` in ScpBindings. The
    /// `caveatsJson` parameter (SCP-OUT-023) carries the §7.3.8
    /// invocation caveats wire form; pass `nil` for a caveat-free token.
    public typealias MintFn = @Sendable (
        _ handle: ContextHandle,
        _ memberDid: String,
        _ capabilities: [String],
        _ proofs: [String]?,
        _ caveatsJson: String?
    ) async throws -> UcanToken

    /// Narrow a UCAN token's caveats. Maps to ``ucanNarrow`` in
    /// ScpBindings (SCP-OUT-023, §7.3.8).
    public typealias NarrowFn = @Sendable (
        _ handle: ContextHandle,
        _ parentToken: String,
        _ childCaveatsJson: String
    ) async throws -> UcanToken

    /// Revoke a UCAN token. Maps to ``ucanRevoke`` in ScpBindings.
    public typealias RevokeFn = @Sendable (
        _ handle: ContextHandle,
        _ token: String,
        _ revokerDid: String
    ) async throws -> Void

    /// Default validate function that delegates to the UniFFI-generated binding.
    public static let defaultValidate: ValidateFn = { handle, token, capability, presentingAgentDid, proofTokens in
        try await ucanValidate(handle: handle, token: token, capability: capability, presentingAgentDid: presentingAgentDid, proofTokens: proofTokens)
    }

    /// Default mint function that delegates to the UniFFI-generated binding.
    public static let defaultMint: MintFn = { handle, memberDid, capabilities, proofs, caveatsJson in
        try await ucanMint(handle: handle, memberDid: memberDid, capabilities: capabilities, proofs: proofs, caveatsJson: caveatsJson)
    }

    /// Default narrow function (SCP-OUT-023) — delegates to the UniFFI-generated binding.
    public static let defaultNarrow: NarrowFn = { handle, parentToken, childCaveatsJson in
        try await ucanNarrow(handle: handle, parentToken: parentToken, childCaveatsJson: childCaveatsJson)
    }

    /// Default revoke function that delegates to the UniFFI-generated binding.
    public static let defaultRevoke: RevokeFn = { handle, token, revokerDid in
        try await ucanRevoke(handle: handle, token: token, revokerDid: revokerDid)
    }

    /// Delegate a UCAN token. Maps to ``ucanDelegate`` in ScpBindings.
    public typealias DelegateFn = @Sendable (
        _ handle: ContextHandle,
        _ delegatorDid: String,
        _ delegateeDid: String,
        _ parentToken: String,
        _ capabilities: [String]
    ) async throws -> UcanToken

    /// Default delegate function — delegates to UniFFI
    /// ``ucanDelegate(handle:delegatorDid:delegateeDid:parentToken:capabilities:)``.
    public static let defaultDelegate: DelegateFn = { handle, delegatorDid, delegateeDid, parentToken, capabilities in
        try await ucanDelegate(handle: handle, delegatorDid: delegatorDid, delegateeDid: delegateeDid, parentToken: parentToken, capabilities: capabilities)
    }
}

