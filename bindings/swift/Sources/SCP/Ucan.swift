)
public func mint(
    handle: ContextHandle,
    issuerDid _: String,
    audienceDid: String,
    capabilities: [UcanCapability],
    expirySecs _: UInt64 = 3600,
    proofs: [String] = [],
    mintFn: UcanBridge.MintFn = UcanBridge.defaultMint
