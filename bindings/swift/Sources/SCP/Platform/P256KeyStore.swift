import Foundation
import Security

// MARK: - P256Backing

/// Where the private half of a P-256 or HPKE P-256 key lives.
///
/// ``AppleKeyCustody`` chooses the backing once, from an enclave availability
/// probe, and records it in each key's companion item at mint (ADR-025
/// criterion 8). Every later operation on the key reads the backing from that
/// record, never from the key type.
nonisolated enum P256Backing: String, Sendable, Equatable, CaseIterable {
    /// The Secure Enclave: `SecKeyCreateRandomKey` with
    /// `kSecAttrTokenIDSecureEnclave`. Reported as `"hardware"` custody.
    case secureEnclave
    /// The platform signer of spec 09 §9.5 on an Apple platform without an
    /// enclave: a permanent Security-framework `SecKey` with no token id.
    /// Reported as `"software"` or `"software_biometric"` custody.
    case software
}

// MARK: - P256KeyStore

/// The store that holds the private half of every P-256 key
/// ``AppleKeyCustody`` mints (`p256` signing keys, `p256-key-event` keys and
/// `hpke-p256` wrapping keys) and runs every operation on it.
///
/// ``KeychainP256KeyStore`` is the only implementation the SDK ships; the
/// public ``AppleKeyCustody`` initializer builds one per ``P256Backing``. The
/// seam exists so that a test can run the adapter's P-256 paths on a host
/// whose unsigned test binary cannot reach the data-protection keychain.
///
/// A key is addressed by its application tag, the UTF-8 bytes of
/// `"scp.key.<id>"`. Every method takes and returns `Data`, so no `SecKey`
/// crosses an isolation boundary, and no method returns private key bytes.
protocol P256KeyStore: Sendable {
    /// Creates a key under `tag` gated by `policy` and returns its 65-byte
    /// uncompressed SEC1 public key (`04 || X || Y`).
    ///
    /// - Throws: ``PlatformError/secureEnclaveKeyCreationFailed(_:)`` when an
    ///   enclave store cannot create the key, or
    ///   ``PlatformError/keychainError(_:)`` when a software store cannot. No
    ///   key is left behind.
    func create(tag: Data, policy: BiometricPolicy) async throws -> Data

    /// The 65-byte uncompressed public key of the key under `tag`.
    ///
    /// - Throws: ``PlatformError/keyNotFound(_:)`` when no key has `tag`.
    func publicKey(tag: Data) async throws -> Data

    /// The DER `ECDSA-Sig-Value` the key under `tag` produces over the
    /// 32-byte `digest`, which is signed as given and not hashed again. The
    /// Rust bridge converts it to the raw low-`s` form and verifies it.
    func sign(tag: Data, digest: Data) async throws -> Data

    /// The 32-byte ECDH shared secret (the x-coordinate) of the key under
    /// `tag` and `peer`, a 65-byte uncompressed point the caller has already
    /// validated as on the curve.
    func agree(tag: Data, peer: Data) async throws -> Data

    /// Deletes the key under `tag`. Returns `false` when no key had `tag`.
    func delete(tag: Data) async throws -> Bool

    /// Whether a key has `tag`.
    func contains(tag: Data) async throws -> Bool
}

// MARK: - KeychainP256KeyStore

/// The production ``P256KeyStore``: every key is a permanent `kSecClassKey`
/// item generated by `SecKeyCreateRandomKey` and never exported.
///
/// - ``P256Backing/secureEnclave``: the key is generated inside the Secure
///   Enclave (`kSecAttrTokenIDSecureEnclave`) and every signature and
///   agreement runs there (ADR-025 criterion 8). A creation failure is
///   ``PlatformError/secureEnclaveKeyCreationFailed(_:)``.
/// - ``P256Backing/software``: the platform signer of spec 09 §9.5 on a host
///   without an enclave, a Security-framework key with no token id. A
///   creation failure is ``PlatformError/keychainError(_:)``.
///
/// Each key is tagged with its application tag and stored under the
/// adapter's access group (ADR-025 criterion 2). On macOS every add, lookup
/// and delete sets `kSecUseDataProtectionKeychain`: an enclave key exists
/// only in the data-protection keychain, and a query without the flag
/// searches the file keychain, finds nothing, and would report a live key as
/// destroyed.
///
/// Every attribute, query and access-control dictionary comes from a pure
/// static function, so host tests assert them without a keychain.
nonisolated struct KeychainP256KeyStore: P256KeyStore {
    /// Where this store's keys live.
    let backing: P256Backing

    /// The Keychain access group every key item is stored under, or `nil`
    /// for the process default.
    let accessGroup: String?

    // MARK: Pure attribute builders

    /// The protection class and flags of a new key's access control.
    struct AccessControlSpec: Equatable {
        let protection: CFString
        let flags: SecAccessControlCreateFlags

        static func == (lhs: Self, rhs: Self) -> Bool {
            (lhs.protection as String) == (rhs.protection as String) && lhs.flags == rhs.flags
        }
    }

    /// The access control of a new key under `backing` and `policy`.
    ///
    /// `.privateKeyUsage` is set only for the enclave backing, the one
    /// backing whose token requires it. Under ``BiometricPolicy/required``
    /// the key adds `.biometryCurrentSet` with the protection class
    /// `WhenUnlockedThisDeviceOnly`, the access control of the adapter's
    /// Ed25519 `.required` items; otherwise the class is
    /// `AfterFirstUnlockThisDeviceOnly` (ADR-025 criterion 2).
    static func accessControlSpec(backing: P256Backing, policy: BiometricPolicy) -> AccessControlSpec {
        var flags: SecAccessControlCreateFlags = []
        if backing == .secureEnclave {
            flags.insert(.privateKeyUsage)
        }
        switch policy {
        case .none:
            return AccessControlSpec(protection: kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly, flags: flags)
        case .required:
            flags.insert(.biometryCurrentSet)
            return AccessControlSpec(protection: kSecAttrAccessibleWhenUnlockedThisDeviceOnly, flags: flags)
        }
    }

    /// The `SecAccessControl` of ``accessControlSpec(backing:policy:)``.
    static func accessControl(backing: P256Backing, policy: BiometricPolicy) throws -> SecAccessControl {
        let spec = accessControlSpec(backing: backing, policy: policy)
        var cfError: Unmanaged<CFError>?
        guard let access = SecAccessControlCreateWithFlags(nil, spec.protection, spec.flags, &cfError) else {
            throw PlatformError.custodyError("Failed to create P-256 key access control: \(describe(cfError))")
        }
        return access
    }

    /// The `SecKeyCreateRandomKey` attributes of a permanent key under `tag`.
    static func createAttributes(
        tag: Data,
        backing: P256Backing,
        accessGroup: String?,
        accessControl: SecAccessControl
    ) -> [String: Any] {
        var privateAttributes: [String: Any] = [
            kSecAttrIsPermanent as String: true,
            kSecAttrApplicationTag as String: tag,
            kSecAttrAccessControl as String: accessControl
        ]
        var attributes: [String: Any] = [
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeySizeInBits as String: 256
        ]
        if backing == .secureEnclave {
            attributes[kSecAttrTokenID as String] = kSecAttrTokenIDSecureEnclave
        }
        #if os(macOS)
            attributes[kSecUseDataProtectionKeychain as String] = true
        #endif
        if let accessGroup {
            privateAttributes[kSecAttrAccessGroup as String] = accessGroup
            attributes[kSecAttrAccessGroup as String] = accessGroup
        }
        attributes[kSecPrivateKeyAttrs as String] = privateAttributes
        return attributes
    }

    /// The query that selects the key under `tag`.
    static func keyQuery(tag: Data, backing: P256Backing, accessGroup: String?) -> [String: Any] {
        var query: [String: Any] = [
            kSecClass as String: kSecClassKey,
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeyClass as String: kSecAttrKeyClassPrivate,
            kSecAttrApplicationTag as String: tag
        ]
        if backing == .secureEnclave {
            query[kSecAttrTokenID as String] = kSecAttrTokenIDSecureEnclave
        }
        #if os(macOS)
            query[kSecUseDataProtectionKeychain as String] = true
        #endif
        if let accessGroup {
            query[kSecAttrAccessGroup as String] = accessGroup
        }
        return query
    }

    private func keyQuery(tag: Data) -> [String: Any] {
        Self.keyQuery(tag: tag, backing: backing, accessGroup: accessGroup)
    }

    /// The name of this store's signer in error messages.
    private var signer: String {
        switch backing {
        case .secureEnclave: "Secure Enclave"
        case .software: "platform signer"
        }
    }

    // MARK: Operations

    func create(tag: Data, policy: BiometricPolicy) throws -> Data {
        let attributes = try Self.createAttributes(
            tag: tag,
            backing: backing,
            accessGroup: accessGroup,
            accessControl: Self.accessControl(backing: backing, policy: policy)
        )
        var cfError: Unmanaged<CFError>?
        guard let key = SecKeyCreateRandomKey(attributes as CFDictionary, &cfError) else {
            let status = Self.status(cfError)
            switch backing {
            case .secureEnclave: throw PlatformError.secureEnclaveKeyCreationFailed(status)
            case .software: throw PlatformError.keychainError(status)
            }
        }
        do {
            return try Self.uncompressedPublicKey(of: key)
        } catch {
            // A key whose public half cannot be read is unusable; remove it so
            // the failed generation leaves nothing behind.
            SecItemDelete(keyQuery(tag: tag) as CFDictionary)
            throw error
        }
    }

    /// Loads the private key reference under `tag`. The reference is a
    /// handle to the key, not its bytes.
    private func load(tag: Data) throws -> SecKey {
        var query = keyQuery(tag: tag)
        query[kSecReturnRef as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne
        var result: AnyObject?
        let status = SecItemCopyMatching(query as CFDictionary, &result)
        switch status {
        case errSecSuccess:
            guard let result, CFGetTypeID(result) == SecKeyGetTypeID() else {
                throw PlatformError.custodyError("Keychain returned no key reference")
            }
            // The type id check above makes this cast exact.
            return result as! SecKey // swiftlint:disable:this force_cast
        case errSecItemNotFound:
            throw PlatformError.keyNotFound(Self.handle(of: tag))
        default:
            throw PlatformError.keychainError(status)
        }
    }

    func publicKey(tag: Data) throws -> Data {
        try Self.uncompressedPublicKey(of: load(tag: tag))
    }

    func sign(tag: Data, digest: Data) throws -> Data {
        let key = try load(tag: tag)
        var cfError: Unmanaged<CFError>?
        guard let der = SecKeyCreateSignature(
            key, .ecdsaSignatureDigestX962SHA256, digest as CFData, &cfError
        ) else {
            throw Self.operationError("\(signer) signing", tag: tag, cfError)
        }
        return der as Data
    }

    func agree(tag: Data, peer: Data) throws -> Data {
        let key = try load(tag: tag)
        let peerKey = try Self.peerKey(peer)
        var cfError: Unmanaged<CFError>?
        guard let secret = SecKeyCopyKeyExchangeResult(
            key, .ecdhKeyExchangeStandard, peerKey, [:] as CFDictionary, &cfError
        ) else {
            throw Self.operationError("\(signer) ECDH", tag: tag, cfError)
        }
        return secret as Data
    }

    func delete(tag: Data) throws -> Bool {
        let status = SecItemDelete(keyQuery(tag: tag) as CFDictionary)
        switch status {
        case errSecSuccess:
            return true
        case errSecItemNotFound:
            return false
        default:
            throw PlatformError.keychainError(status)
        }
    }

    func contains(tag: Data) throws -> Bool {
        var query = keyQuery(tag: tag)
        query[kSecMatchLimit as String] = kSecMatchLimitOne
        let status = SecItemCopyMatching(query as CFDictionary, nil)
        switch status {
        case errSecSuccess:
            return true
        case errSecItemNotFound:
            return false
        default:
            throw PlatformError.keychainError(status)
        }
    }
}

// MARK: - Shared SecKey helpers

extension KeychainP256KeyStore {
    /// The 65-byte uncompressed SEC1 public key of a P-256 private key.
    static func uncompressedPublicKey(of key: SecKey) throws -> Data {
        var cfError: Unmanaged<CFError>?
        guard
            let publicKey = SecKeyCopyPublicKey(key),
            let external = SecKeyCopyExternalRepresentation(publicKey, &cfError) as Data?
        else {
            throw PlatformError.custodyError(
                "Failed to export the P-256 public key: \(describe(cfError))"
            )
        }
        guard external.count == 65, external.first == 0x04 else {
            throw PlatformError.custodyError(
                "P-256 public key export returned \(external.count) bytes, expected 65"
            )
        }
        return external
    }

    /// A public `SecKey` for a 65-byte uncompressed peer point.
    static func peerKey(_ peer: Data) throws -> SecKey {
        let attributes: [String: Any] = [
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeyClass as String: kSecAttrKeyClassPublic,
            kSecAttrKeySizeInBits as String: 256
        ]
        var cfError: Unmanaged<CFError>?
        guard let key = SecKeyCreateWithData(peer as CFData, attributes as CFDictionary, &cfError) else {
            throw PlatformError.custodyError("Invalid P-256 peer public key: \(describe(cfError))")
        }
        return key
    }

    /// The key id an application tag names, for error messages.
    static func handle(of tag: Data) -> String {
        let text = String(bytes: tag, encoding: .utf8) ?? tag.base64EncodedString()
        let prefix = "scp.key."
        return text.hasPrefix(prefix) ? String(text.dropFirst(prefix.count)) : text
    }

    /// The `OSStatus` a Security framework `CFError` carries.
    static func status(_ cfError: Unmanaged<CFError>?) -> OSStatus {
        guard let cfError else { return errSecInternalError }
        return OSStatus(truncatingIfNeeded: CFErrorGetCode(cfError.takeRetainedValue()))
    }

    /// A readable description of a Security framework `CFError`.
    static func describe(_ cfError: Unmanaged<CFError>?) -> String {
        cfError.map { ($0.takeRetainedValue() as Error).localizedDescription } ?? "unknown error"
    }

    /// The typed error of a failed key operation: a cancelled or failed user
    /// authentication is ``PlatformError/biometricAuthenticationFailed(_:)``,
    /// anything else ``PlatformError/custodyError(_:)``.
    static func operationError(
        _ operation: String,
        tag: Data,
        _ cfError: Unmanaged<CFError>?
    ) -> PlatformError {
        guard let cfError else {
            return .custodyError("\(operation) failed for key id '\(handle(of: tag))'")
        }
        let error = cfError.takeRetainedValue()
        let code = OSStatus(truncatingIfNeeded: CFErrorGetCode(error))
        let detail = (error as Error).localizedDescription
        switch code {
        case errSecUserCanceled, errSecAuthFailed, errSecInteractionNotAllowed:
            return .biometricAuthenticationFailed(
                "\(operation) for key id '\(handle(of: tag))' (OSStatus \(code)): \(detail)"
            )
        default:
            return .custodyError("\(operation) failed for key id '\(handle(of: tag))': \(detail)")
        }
    }
}
