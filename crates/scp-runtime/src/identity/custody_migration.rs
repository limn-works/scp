//! Key custody migration protocol (spec §3.2.1).
//!
//! "The identity layer abstracts custody. The user authenticates however they
//! choose; under the hood it resolves to a protocol-level DID. Migration
//! between custody methods is possible without changing identity." — §3.2
//!
//! This module defines the wire types for custody migration requests and
//! implements the 5-step custody migration state machine. Migration changes
//! the custody backend — an encrypted key file on disk and the keystore the
//! operating system runs are the two a caller names — without altering the
//! user's DID. The active signing key
//! (`#active`) is rotated to a new key generated by the target custody
//! provider; the identity key (`#0`) and DID remain stable.
//!
//! # Migration Steps (spec §3.2.1)
//!
//! 1. **Initiate** — The target custody provider generates a new Ed25519
//!    keypair. The new public key is captured in a [`CustodyMigrationRequest`].
//! 2. **Authorize** — The current `#active` and `#0` keys sign the migration
//!    request to prove consent and continuity.
//! 3. **Rotate** — The DID document is updated to replace the `#active`
//!    verification method with the new public key. This update is signed by
//!    the identity key (`#0`) per ADR-003 §4a and published to DHT.
//! 4. **Reissue** — Existing UCAN tokens signed by the old active key are
//!    revoked and reissued under the new active key. Attestations signed by
//!    the old key are re-signed (spec §3.2.1 step 4).
//! 5. **Destroy** — After verifying DID document propagation, the old active
//!    key material is destroyed in the previous custody provider.
//!
//! See spec §3.2.1 (Key Custody Migration Protocol) and §9.12 (Key Rotation).

use serde::{Deserialize, Serialize};

use scp_did::DID;

use scp_clock::Clock;

// Re-use CustodyType from scp-platform to avoid duplication.
// CustodyType is already defined in scp_platform::traits but scp-core doesn't
// depend on scp-platform. We define the migration-level custody type enum here
// to keep scp-core self-contained.

// ---------------------------------------------------------------------------
// CustodyMigrationTarget
// ---------------------------------------------------------------------------

/// The custody backend a migration moves the `#active` key into (spec §3.2).
///
/// A caller naming a custody backend names one of these two. The vocabulary
/// carries no in-memory value: an in-memory custody keeps no key across a
/// restart, so migrating an identity into one destroys the identity's `#active`
/// key, and a caller has no reason to ask for that.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CustodyMigrationTarget {
    /// A key file on disk, encrypted under a passphrase.
    EncryptedFile,
    /// The keystore the operating system runs (Apple Keychain, Android
    /// Keystore, Windows credential manager).
    OsKeystore,
}

// ---------------------------------------------------------------------------
// CustodyMigrationRequest
// ---------------------------------------------------------------------------

/// A request to migrate key custody from one provider to another (spec §3.2).
///
/// The request captures the new active public key generated by the target
/// custody provider, the target custody type, and the request timestamp.
/// The request must be signed by the current active key to prove consent.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CustodyMigrationRequest {
    /// Ed25519 public key bytes (32 bytes) generated by the target custody
    /// provider. This will become the new `#active` verification method.
    #[serde(with = "serde_bytes")]
    pub new_active_pubkey: Vec<u8>,
    /// The custody type being migrated to.
    pub target_custody_type: CustodyMigrationTarget,
    /// Unix timestamp (milliseconds) when the migration was requested.
    pub requested_at: u64,
}

// ---------------------------------------------------------------------------
// CustodyMigrationStep
// ---------------------------------------------------------------------------

/// The current step in the custody migration protocol.
///
/// Migration is a 5-step process. Each step must complete before the next
/// can begin. If any step fails, the migration is rolled back to the
/// previous custody state.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CustodyMigrationStep {
    /// Step 1: Migration requested, new key generated by target provider.
    Requested,
    /// Step 2: Current active key has signed the migration request.
    Authorized,
    /// Step 3: DID document updated with new `#active` verification method.
    Rotated,
    /// Step 4: UCAN tokens reissued under the new active key.
    Reissued,
    /// Step 5: Old key material destroyed in previous custody provider.
    Completed,
}

// ---------------------------------------------------------------------------
// CustodyMigrationStatus
// ---------------------------------------------------------------------------

/// Status of an in-progress or completed custody migration.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CustodyMigrationStatus {
    /// The migration request that initiated this migration.
    pub request: CustodyMigrationRequest,
    /// The current step in the migration protocol.
    pub current_step: CustodyMigrationStep,
    /// Unix timestamp (milliseconds) when the current step was reached.
    pub step_reached_at: u64,
    /// If the migration failed, a description of the failure.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub failure_reason: Option<String>,
}

// ---------------------------------------------------------------------------
// CustodyMigrationError — orchestrator-level error
// ---------------------------------------------------------------------------

/// Errors produced by the custody migration orchestrator.
///
/// Step 1 (key generation) and step 2 (authorization) failures are fatal —
/// the orchestrator cannot proceed without valid key material and consent.
/// Steps 3–5 failures are recorded in `CustodyMigrationResult::failure_reason`.
#[derive(Debug, thiserror::Error)]
pub enum CustodyMigrationError {
    /// Step 1 failed: new key generation in target custody provider.
    #[error("key generation failed (step 1): {0}")]
    KeyGenerationFailed(String),

    /// Step 2 failed: authorization by current keys.
    #[error("authorization failed (step 2): {0}")]
    AuthorizationFailed(String),

    /// Step 3 failed: DID document rotation.
    #[error("DID document rotation failed (step 3): {0}")]
    RotationFailed(String),

    /// Step 4 failed: UCAN revocation and reissuance.
    #[error("UCAN reissuance failed (step 4): {0}")]
    ReissuanceFailed(String),

    /// Step 5 failed: old key destruction.
    ///
    /// This is non-fatal per spec §3.2.1: "The migration is still complete —
    /// the DID document references the new key. The old key is orphaned but
    /// harmless."
    #[error("old key destruction failed (step 5): {0}")]
    DestructionFailed(String),

    /// The new active public key is invalid (wrong length).
    #[error("invalid new active public key: expected 32 bytes, got {0}")]
    InvalidPublicKey(usize),
}

// ---------------------------------------------------------------------------
// CustodyMigrationResult — outcome of the full migration
// ---------------------------------------------------------------------------

/// Outcome of executing the custody migration protocol.
///
/// Contains the final status of each step. The DID is unchanged (custody
/// migration preserves the DID string by design — only `#active` rotates).
///
/// See spec §3.2.1.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CustodyMigrationResult {
    /// The DID that underwent custody migration (unchanged).
    pub did: DID,

    /// The target custody type that was migrated to.
    pub target: CustodyMigrationTarget,

    /// Whether step 1 (key generation) completed.
    pub key_generated: bool,

    /// Whether step 2 (authorization) completed.
    pub authorized: bool,

    /// Whether step 3 (DID document rotation) completed.
    pub did_document_rotated: bool,

    /// Whether step 4 (UCAN reissuance + attestation re-sign) completed.
    pub ucans_reissued: bool,

    /// Whether step 5 (old key destruction) completed.
    ///
    /// `false` is non-fatal per spec §3.2.1 — the old key is orphaned but
    /// harmless since UCAN tokens signed by it are revoked and the DID
    /// document references the new key.
    pub old_key_destroyed: bool,

    /// Contexts where MLS Update proposals were issued successfully.
    pub updated_contexts: Vec<String>,

    /// Contexts where MLS Update failed.
    pub failed_contexts: Vec<String>,

    /// Unix timestamp (milliseconds) when migration was initiated.
    pub initiated_at: u64,

    /// Unix timestamp (milliseconds) when migration completed.
    pub completed_at: u64,

    /// If the migration failed at any step, the reason.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub failure_reason: Option<String>,
}

// ---------------------------------------------------------------------------
// CustodyMigrationBackend — trait for platform-specific migration operations
// ---------------------------------------------------------------------------

/// Backend trait for platform-specific custody migration operations.
///
/// The orchestrator defines step ordering and rollback semantics; the backend
/// provides the concrete key generation, DID document update, UCAN
/// revocation, MLS update, attestation re-sign, and key destruction
/// operations.
///
/// SDK integration layers implement this trait to wire the orchestrator into
/// the actual custody provider, DID document publisher, and UCAN store.
///
/// See spec §3.2.1.
pub trait CustodyMigrationBackend {
    /// Step 1: Generate a new Ed25519 keypair in the target custody provider.
    ///
    /// Returns the 32-byte public key of the newly generated keypair.
    ///
    /// # Errors
    ///
    /// Returns a description string if key generation fails.
    fn generate_key(&self, target: CustodyMigrationTarget) -> Result<Vec<u8>, String>;

    /// Step 2: Authorize the migration by signing the request with the
    /// current `#active` and `#0` keys.
    ///
    /// The backend verifies that the request was initiated by the identity
    /// owner (device-local authentication) and signs the request.
    ///
    /// # Errors
    ///
    /// Returns a description string if authorization fails.
    fn authorize(&self, request: &CustodyMigrationRequest) -> Result<(), String>;

    /// Step 3: Update the DID document with the new `#active` verification
    /// method, sign with `#0`, and publish to both resolution layers.
    ///
    /// Also issues MLS Update proposals in the given context IDs.
    ///
    /// Returns a tuple of (`succeeded_context_ids`, `failed_context_ids`).
    ///
    /// # Errors
    ///
    /// Returns a description string if the DID document update itself fails.
    /// Per-context MLS Update failures are returned in the failed list, not
    /// as errors.
    fn rotate_did_document(
        &self,
        did: &DID,
        request: &CustodyMigrationRequest,
        context_ids: &[String],
    ) -> Result<(Vec<String>, Vec<String>), String>;

    /// Step 4: Revoke all UCAN tokens signed by the old `#active` key and
    /// reissue them under the new key. Also re-sign attestations.
    ///
    /// # Errors
    ///
    /// Returns a description string if revocation or reissuance fails.
    fn reissue_credentials(
        &self,
        did: &DID,
        request: &CustodyMigrationRequest,
    ) -> Result<(), String>;

    /// Step 5: Destroy the old `#active` key material in the source custody
    /// provider.
    ///
    /// This step verifies DID document propagation before destruction:
    /// the updated document must be resolvable from at least one relay and
    /// DHT node.
    ///
    /// # Errors
    ///
    /// Returns a description string if destruction fails. This is non-fatal
    /// per spec §3.2.1.
    fn destroy_old_key(&self, did: &DID) -> Result<(), String>;
}

// ---------------------------------------------------------------------------
// CustodyMigrationOrchestrator
// ---------------------------------------------------------------------------

/// Orchestrates the 5-step custody migration protocol (§3.2.1).
///
/// The orchestrator coordinates key generation, authorization, DID document
/// rotation, UCAN reissuance, attestation re-signing, and old key destruction
/// in dependency order. Each step must complete before the next begins.
///
/// Step operations are delegated to a [`CustodyMigrationBackend`]
/// implementation, which provides platform-specific custody, DID, and UCAN
/// operations.
///
/// # Failure semantics (per spec §3.2.1)
///
/// - Step 1 or 2 failure: No state change. Abort cleanly.
/// - Step 3 failure (partial publication): Safe — peers with old document
///   continue to work. The `RepublishManager` converges on retry.
/// - Step 4 failure: The SDK queues failed operations for retry.
/// - Step 5 failure: Non-fatal — old key is orphaned but harmless.
///
/// # Usage
///
/// ```rust,ignore
/// let backend = MyMigrationBackend::new(/* ... */);
/// let orchestrator = CustodyMigrationOrchestrator::new(
///     did.clone(),
///     CustodyMigrationTarget::OsKeystore,
///     vec!["ctx-1".into(), "ctx-2".into()],
/// );
/// let result = orchestrator.execute(&backend, &clock).await?;
/// ```
///
/// See spec §3.2.1 (Key Custody Migration Protocol).
pub struct CustodyMigrationOrchestrator {
    /// The DID performing custody migration.
    did: DID,

    /// The target custody type to migrate to.
    target: CustodyMigrationTarget,

    /// Active context IDs where MLS Update proposals should be issued.
    context_ids: Vec<String>,
}

impl CustodyMigrationOrchestrator {
    /// Creates a new orchestrator for the given DID and target custody type.
    ///
    /// # Arguments
    ///
    /// * `did` — The DID performing custody migration.
    /// * `target` — The target custody type to migrate to.
    /// * `context_ids` — All context IDs where this DID is an active member.
    #[must_use]
    pub const fn new(did: DID, target: CustodyMigrationTarget, context_ids: Vec<String>) -> Self {
        Self {
            did,
            target,
            context_ids,
        }
    }

    /// Executes the full 5-step custody migration protocol.
    ///
    /// Steps execute in strict dependency order: 1→2→3→4→5.
    ///
    /// If steps 1 or 2 fail, the migration aborts with no state change and
    /// returns the corresponding [`CustodyMigrationError`].
    ///
    /// If step 3 fails at the DID document level, the migration aborts.
    /// Per-context MLS Update failures within step 3 are recorded in
    /// `CustodyMigrationResult::failed_contexts` but do not abort the
    /// migration.
    ///
    /// If step 4 fails, the error is recorded but the migration result is
    /// still returned (the DID document already points to the new key).
    ///
    /// If step 5 fails, the error is recorded but the migration is considered
    /// successful — the old key is orphaned but harmless per spec §3.2.1.
    ///
    /// # Errors
    ///
    /// Returns [`CustodyMigrationError`] for fatal failures in steps 1–3.
    /// Steps 4–5 failures are recorded in the result, not as errors.
    #[allow(clippy::unused_async)] // async by design: SDK integration layer adds await points
    #[allow(clippy::future_not_send)] // backend trait object is not Sync by design
    pub async fn execute(
        &self,
        backend: &dyn CustodyMigrationBackend,
        clock: &dyn Clock,
    ) -> Result<CustodyMigrationResult, CustodyMigrationError> {
        let initiated_at = clock.now_millis();

        // Step 1: Generate new key in target custody provider.
        let new_pubkey = backend
            .generate_key(self.target)
            .map_err(CustodyMigrationError::KeyGenerationFailed)?;

        // Validate key length.
        if new_pubkey.len() != 32 {
            return Err(CustodyMigrationError::InvalidPublicKey(new_pubkey.len()));
        }

        let request = CustodyMigrationRequest {
            new_active_pubkey: new_pubkey,
            target_custody_type: self.target,
            requested_at: initiated_at,
        };

        // Step 2: Authorize the migration.
        backend
            .authorize(&request)
            .map_err(CustodyMigrationError::AuthorizationFailed)?;

        // Step 3: Rotate the DID document and issue MLS Update proposals.
        let (updated_contexts, failed_contexts) = backend
            .rotate_did_document(&self.did, &request, &self.context_ids)
            .map_err(CustodyMigrationError::RotationFailed)?;

        // Step 4: Revoke old UCANs and reissue under new key, re-sign
        // attestations. Failure here is recorded but does not abort — the
        // DID document already points to the new key.
        let mut failure_reason: Option<String> = None;
        let ucans_reissued = match backend.reissue_credentials(&self.did, &request) {
            Ok(()) => true,
            Err(reason) => {
                failure_reason = Some(format!("UCAN reissuance failed (step 4): {reason}"));
                false
            }
        };

        // Step 5: Destroy old key material. Non-fatal per spec §3.2.1.
        let old_key_destroyed = match backend.destroy_old_key(&self.did) {
            Ok(()) => true,
            Err(reason) => {
                let step5_msg = format!("old key destruction failed (step 5, non-fatal): {reason}");
                failure_reason = Some(match failure_reason {
                    Some(existing) => format!("{existing}; {step5_msg}"),
                    None => step5_msg,
                });
                false
            }
        };

        let completed_at = clock.now_millis();

        Ok(CustodyMigrationResult {
            did: self.did.clone(),
            target: self.target,
            key_generated: true,
            authorized: true,
            did_document_rotated: true,
            ucans_reissued,
            old_key_destroyed,
            updated_contexts,
            failed_contexts,
            initiated_at,
            completed_at,
            failure_reason,
        })
    }

    /// Returns the DID this orchestrator is migrating.
    #[must_use]
    pub const fn did(&self) -> &DID {
        &self.did
    }

    /// Returns the target custody type.
    #[must_use]
    pub const fn target(&self) -> CustodyMigrationTarget {
        self.target
    }

    /// Returns the context IDs included in migration.
    #[must_use]
    pub fn context_ids(&self) -> &[String] {
        &self.context_ids
    }
}

