    /// A mock `CustodyMigrationBackend` that succeeds for all operations by
    /// default. Individual steps can be configured to fail.
    struct MockMigrationBackend {
        /// If set, `generate_key` returns this error.
        generate_key_error: Option<String>,
        /// The public key to return from `generate_key`.
        generated_pubkey: Vec<u8>,
        /// If set, `authorize` returns this error.
        authorize_error: Option<String>,
        /// If set, `rotate_did_document` returns this error.
        rotate_error: Option<String>,
        /// Contexts that fail during MLS Update in step 3.
        mls_failed_contexts: Vec<String>,
        /// If set, `reissue_credentials` returns this error.
        reissue_error: Option<String>,
        /// If set, `destroy_old_key` returns this error.
        destroy_error: Option<String>,
    }

    impl MockMigrationBackend {
        fn new() -> Self {
            Self {
                generate_key_error: None,
                generated_pubkey: vec![0xAA; 32],
                authorize_error: None,
                rotate_error: None,
                mls_failed_contexts: Vec::new(),
                reissue_error: None,
                destroy_error: None,
            }
        }
    }

    impl CustodyMigrationBackend for MockMigrationBackend {
        fn generate_key(&self, _target: CustodyMigrationTarget) -> Result<Vec<u8>, String> {
            if let Some(ref err) = self.generate_key_error {
                return Err(err.clone());
            }
            Ok(self.generated_pubkey.clone())
        }

        fn authorize(&self, _request: &CustodyMigrationRequest) -> Result<(), String> {
            if let Some(ref err) = self.authorize_error {
                return Err(err.clone());
            }
            Ok(())
        }

        fn rotate_did_document(
            &self,
            _did: &DID,
            _request: &CustodyMigrationRequest,
            context_ids: &[String],
        ) -> Result<(Vec<String>, Vec<String>), String> {
            if let Some(ref err) = self.rotate_error {
                return Err(err.clone());
            }
            let mut succeeded = Vec::new();
            let mut failed = Vec::new();
            for ctx in context_ids {
                if self.mls_failed_contexts.contains(ctx) {
                    failed.push(ctx.clone());
                } else {
                    succeeded.push(ctx.clone());
                }
            }
            Ok((succeeded, failed))
        }

        fn reissue_credentials(
            &self,
            _did: &DID,
            _request: &CustodyMigrationRequest,
        ) -> Result<(), String> {
            if let Some(ref err) = self.reissue_error {
                return Err(err.clone());
            }
            Ok(())
        }

        fn destroy_old_key(&self, _did: &DID) -> Result<(), String> {
            if let Some(ref err) = self.destroy_error {
                return Err(err.clone());
            }
            Ok(())
        }
    }

