/// Size of a raw Ed25519 or X25519 public key in bytes.
const PUBLIC_KEY_SIZE: usize = 32;

/// Size of a raw Ed25519 signature in bytes.
const SIGNATURE_SIZE: usize = 64;

/// The randomness provider of [`InMemoryMlsProvider`].
type BaseRand = <InMemoryMlsProvider as OpenMlsProvider>::RandProvider;

/// The crypto provider of [`InMemoryMlsProvider`].
type BaseCrypto = <InMemoryMlsProvider as OpenMlsProvider>::CryptoProvider;

/// The storage provider of [`InMemoryMlsProvider`].
type BaseStorage = <InMemoryMlsProvider as OpenMlsProvider>::StorageProvider;

/// The error type [`BaseRand`] reports.
type BaseRandError = <BaseRand as OpenMlsRand>::Error;

// ---------------------------------------------------------------------------
// Randomness transcript
// ---------------------------------------------------------------------------

/// What a [`TranscriptRand`] does with each draw.
#[derive(Debug)]
enum TranscriptMode {
    /// Draw from the real generator and append each result to the log.
    Record(Vec<Vec<u8>>),
    /// Return the next logged result whose length matches the request.
    Replay(VecDeque<Vec<u8>>),
}

/// An [`OpenMlsRand`] that records the draws of one `KeyPackage` build so a
/// second build can repeat them.
///
/// Recording takes every byte from the real generator ([`BaseRand`]) and keeps
/// a copy, so the entropy of the recorded build is exactly the entropy of an
/// ordinary build. Replaying hands those same bytes back in the order they were
/// drawn. A replay request whose length does not match the next logged draw —
/// which a change in `openmls`'s internal draw sequence would cause — falls
/// through to the real generator, and [`finish_key_package`] then rejects the
/// resulting `KeyPackage` because its keys no longer match the attestation.
#[derive(Debug)]
struct TranscriptRand<'a> {
    /// The real generator every recorded draw comes from, and the fallback for
    /// a replay draw the log cannot satisfy.
    inner: &'a BaseRand,
    /// The recorded or remaining draws.
    mode: Mutex<TranscriptMode>,
}

impl<'a> TranscriptRand<'a> {
    /// Creates a recording transcript over `inner`.
    const fn recording(inner: &'a BaseRand) -> Self {
        Self {
            inner,
            mode: Mutex::new(TranscriptMode::Record(Vec::new())),
        }
    }

    /// Creates a transcript that replays `draws` in order.
    fn replaying(inner: &'a BaseRand, draws: Vec<Vec<u8>>) -> Self {
        Self {
            inner,
            mode: Mutex::new(TranscriptMode::Replay(draws.into())),
        }
    }

    /// Consumes the transcript and returns the draws it recorded.
    fn into_recorded(self) -> Vec<Vec<u8>> {
        match self
            .mode
            .into_inner()
            .unwrap_or_else(PoisonError::into_inner)
        {
            TranscriptMode::Record(log) => log,
            TranscriptMode::Replay(remaining) => remaining.into(),
        }
    }

    /// Returns `len` bytes, recording or replaying them per the mode.
    fn draw(&self, len: usize) -> Result<Vec<u8>, BaseRandError> {
        let mut mode = self.mode.lock().unwrap_or_else(PoisonError::into_inner);
        match &mut *mode {
            TranscriptMode::Record(log) => {
                let bytes = self.inner.random_vec(len)?;
                log.push(bytes.clone());
                Ok(bytes)
            }
            TranscriptMode::Replay(remaining) => {
                if remaining.front().is_some_and(|next| next.len() == len) {
                    // `front` matched, so `pop_front` yields that same element.
                    remaining
                        .pop_front()
                        .map_or_else(|| self.inner.random_vec(len), Ok)
                } else {
                    self.inner.random_vec(len)
                }
            }
        }
    }
}

impl OpenMlsRand for TranscriptRand<'_> {
    type Error = BaseRandError;

    fn random_array<const N: usize>(&self) -> Result<[u8; N], Self::Error> {
        let drawn = self.draw(N)?;
        let mut out = [0u8; N];
        // `draw` returns exactly `N` bytes on both paths: the recording path
        // asks the real generator for `N`, and the replay path only pops an
        // entry whose length is `N`.
        if drawn.len() == N {
            out.copy_from_slice(&drawn);
            Ok(out)
        } else {
            self.inner.random_array::<N>()
        }
    }

    fn random_vec(&self, len: usize) -> Result<Vec<u8>, Self::Error> {
        self.draw(len)
    }
}

/// An [`OpenMlsProvider`] that swaps one [`InMemoryMlsProvider`]'s randomness
/// source for a [`TranscriptRand`], leaving its crypto and storage untouched.
#[derive(Debug)]
struct TranscriptProvider<'a> {
    /// The provider whose crypto and storage this wrapper forwards to.
    inner: &'a InMemoryMlsProvider,
    /// The recording or replaying randomness source `openmls` draws from.
    rand: TranscriptRand<'a>,
}

impl<'a> TranscriptProvider<'a> {
    /// Wraps `inner` with a recording transcript.
    fn recording(inner: &'a InMemoryMlsProvider) -> Self {
        Self {
            inner,
            rand: TranscriptRand::recording(inner.rand()),
        }
    }

    /// Wraps `inner` with a transcript that replays `draws`.
    fn replaying(inner: &'a InMemoryMlsProvider, draws: Vec<Vec<u8>>) -> Self {
        Self {
            inner,
            rand: TranscriptRand::replaying(inner.rand(), draws),
        }
    }

    /// Consumes the wrapper and returns the draws its transcript recorded.
    fn into_recorded(self) -> Vec<Vec<u8>> {
        self.rand.into_recorded()
    }
}

impl<'a> OpenMlsProvider for TranscriptProvider<'a> {
    type CryptoProvider = BaseCrypto;
    type RandProvider = TranscriptRand<'a>;
    type StorageProvider = BaseStorage;

    fn storage(&self) -> &Self::StorageProvider {
        self.inner.storage()
    }

    fn crypto(&self) -> &Self::CryptoProvider {
        self.inner.crypto()
    }

    fn rand(&self) -> &Self::RandProvider {
        &self.rand
    }
}

