    use scp_clock::SystemClock;
    use scp_did::SigningKeyId;

    const WRAPPING_KEY: [u8; 32] = [0x11; 32];

    fn credential() -> ScpCredential {
        ScpCredential::new(
            "did:key:z6MkTestKeyPackageAttestationMint".to_owned(),
            None,
            SigningKeyId::Active,
        )
        .expect("test credential")
    }

    #[test]
    fn finished_leaf_carries_the_attestation_extension() {
        let key = SigningKey::generate(&mut OsRng);
        let (bundle, _signer, _provider) =
            mint_key_package_for_testing(&credential(), &WRAPPING_KEY, &SystemClock, &key)
                .expect("mint");

        let extension = bundle
            .key_package()
            .leaf_node()
            .extensions()
            .unknown(SCP_KEYPACKAGE_ATTESTATION_EXTENSION_TYPE);
        assert!(
            extension.is_some(),
            "a minted KeyPackage leaf must carry the 0xFF03 scp_keypackage_attestation extension"
        );
    }

    #[test]
    fn attestation_binds_the_four_keys_the_leaf_actually_carries() {
        let key = SigningKey::generate(&mut OsRng);
        let (bundle, _signer, _provider) =
            mint_key_package_for_testing(&credential(), &WRAPPING_KEY, &SystemClock, &key)
                .expect("mint");

        let leaf = bundle.key_package().leaf_node();
        let attestation = KeyPackageAttestation::extract_attestation(leaf.extensions())
            .expect("parse attestation")
            .expect("attestation present");

        assert_eq!(
            attestation.leaf_signature_key,
            fixed_32(leaf.signature_key().as_slice(), "sig").expect("sig bytes"),
            "the attestation must bind the leaf's actual signature_key (§9.7.1 check 4)"
        );
        assert_eq!(
            attestation.leaf_encryption_key,
            leaf_encryption_key_bytes(leaf).expect("enc bytes"),
            "the attestation must bind the leaf's actual encryption_key (§9.7.1 check 5)"
        );
        assert_eq!(
            attestation.init_key,
            fixed_32(bundle.key_package().hpke_init_key().as_slice(), "init").expect("init bytes"),
            "the attestation must bind the KeyPackage's actual init_key (§9.7.1 check 7)"
        );
        assert_eq!(
            attestation.wrapping_key, WRAPPING_KEY,
            "the attestation must bind the leaf's 0xFF01 wrapping key (§9.7.1 check 6)"
        );
        assert_ne!(
            attestation.init_key, attestation.leaf_encryption_key,
            "RFC 9420 §10.1 requires init_key and encryption_key to differ"
        );
    }

    #[test]
    fn attestation_window_equals_the_leaf_lifetime() {
        let key = SigningKey::generate(&mut OsRng);
        let (bundle, _signer, _provider) =
            mint_key_package_for_testing(&credential(), &WRAPPING_KEY, &SystemClock, &key)
                .expect("mint");

        let lifetime = *bundle.key_package().life_time();
        let attestation = KeyPackageAttestation::extract_attestation(
            bundle.key_package().leaf_node().extensions(),
        )
        .expect("parse attestation")
        .expect("attestation present");

        assert_eq!(
            attestation.issued_at,
            lifetime.not_before(),
            "§9.7.1 check 11 pins issued_at to Lifetime.not_before"
        );
        assert_eq!(
            attestation.expires_at,
            lifetime.not_after(),
            "§9.7.1 check 11 pins expires_at to Lifetime.not_after"
        );
    }

    #[test]
    fn signature_verifies_against_the_signing_key() {
        let key = SigningKey::generate(&mut OsRng);
        let prepared =
            prepare_key_package(&credential(), &WRAPPING_KEY, &SystemClock).expect("prepare");
        let hash = prepared.attestation_signing_hash();
        let signature = key.sign(&hash).to_bytes();
        let (bundle, _signer, _provider) = finish_key_package(prepared, signature).expect("finish");

        let attestation = KeyPackageAttestation::extract_attestation(
            bundle.key_package().leaf_node().extensions(),
        )
        .expect("parse attestation")
        .expect("attestation present");

        key.verifying_key()
            .verify_strict(
                &attestation.signing_hash(),
                &ed25519_dalek::Signature::from_bytes(&attestation.signature),
            )
            .expect("the minted attestation must verify against the signing key");
    }

    #[test]
    fn replay_reproduces_the_probe_keys() {
        // Two finishes of two separate prepares must not collide, and each
        // finish must reproduce its own prepare's keys — the binding check
        // inside `finish_key_package` is what proves the second half.
        let key = SigningKey::generate(&mut OsRng);
        let first = mint_key_package_for_testing(&credential(), &WRAPPING_KEY, &SystemClock, &key)
            .expect("first mint");
        let second = mint_key_package_for_testing(&credential(), &WRAPPING_KEY, &SystemClock, &key)
            .expect("second mint");

        assert_ne!(
            first.0.key_package().hpke_init_key().as_slice(),
            second.0.key_package().hpke_init_key().as_slice(),
            "each mint must draw a fresh init_key"
        );
    }

    #[test]
    fn minted_attestation_passes_the_pure_verifier() {
        use crate::keypackage_attestation::AttestationLeafGroundTruth;
        use scp_did::DidDocument;

        let key = SigningKey::generate(&mut OsRng);
        let credential = credential();
        let (bundle, _signer, _provider) =
            mint_key_package_for_testing(&credential, &WRAPPING_KEY, &SystemClock, &key)
                .expect("mint");

        let leaf = bundle.key_package().leaf_node();
        let attestation = KeyPackageAttestation::extract_attestation(leaf.extensions())
            .expect("parse attestation")
            .expect("attestation present");

        let leaf_signature_key = fixed_32(leaf.signature_key().as_slice(), "sig").expect("sig");
        let leaf_encryption_key = leaf_encryption_key_bytes(leaf).expect("enc");
        let kp_init_key =
            fixed_32(bundle.key_package().hpke_init_key().as_slice(), "init").expect("init");
        let lifetime = *bundle.key_package().life_time();

        let ground_truth = AttestationLeafGroundTruth {
            credential: &credential,
            leaf_signature_key: &leaf_signature_key,
            leaf_encryption_key: &leaf_encryption_key,
            leaf_wrapping_key: &WRAPPING_KEY,
            leaf_lifetime_not_before: lifetime.not_before(),
            leaf_lifetime_not_after: lifetime.not_after(),
            trigger: crate::keypackage_attestation::AttestationTrigger::Add {
                kp_init_key: &kp_init_key,
            },
        };

        let document = DidDocument::new(
            &credential.did,
            &[0x42u8; 32],
            &key.verifying_key().to_bytes(),
            &[0u8; 32],
        );

        let now = SystemClock.now_secs();
        verify_attestation_with_resolution(&attestation, &ground_truth, &document, now, now)
            .expect("a freshly minted attestation must pass §9.7.1 checks 1–13");
    }
