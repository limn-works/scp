/// Builds a `KeyPackage` whose leaf carries neither SCP leaf extension.
///
/// The leaf omits both the `0xFF01` `scp_wrapping_key` extension and the
/// `0xFF03` `scp_keypackage_attestation` extension, which is what a
/// non-conformant implementation publishes.
///
/// Every SCP mint path carries both extensions, so no conformant peer produces
/// this shape. A receiver still has to reject it, because a peer chooses what
/// it publishes and a verifier trusts none of it: §9.7.1 rejects the
/// unattested leaf, and ADR-057's sender-key INVARIANT 3 rejects the leaf no
/// peer can HPKE-seal to. This fixture is how a test hands a receiver that
/// input.
///
/// This is an adversarial fixture, not a stand-in for a mint. It is gated on
/// `testing` so no shipped artifact carries it, and nothing in the crate calls
/// it — a caller that wants a real `KeyPackage` takes
/// [`prepare_key_package`]/[`finish_key_package`] or
/// [`mint_key_package_for_testing`], each of which produces both extensions.
///
/// # Errors
///
/// Returns [`MlsError::CredentialSerializationFailed`] if `credential` cannot
/// be serialized, and [`MlsError::KeyPackageGenerationFailed`] if the leaf
/// signature keypair or the `KeyPackage` cannot be built.
#[cfg(any(test, feature = "testing"))]
pub fn mint_non_conformant_key_package_for_testing(
    credential: &ScpCredential,
    clock: &dyn Clock,
) -> Result<(KeyPackageBundle, SignatureKeyPair, InMemoryMlsProvider), MlsError> {
    let signer = SignatureKeyPair::new(SCP_CIPHERSUITE.signature_algorithm())
        .map_err(|e| MlsError::KeyPackageGenerationFailed(format!("signer generation: {e}")))?;
    let provider = InMemoryMlsProvider::default();
    signer
        .store(provider.storage())
        .map_err(|e| MlsError::StorageError(format!("storing leaf signature keypair: {e}")))?;

    let bundle = build_key_package(
        &provider,
        &signer,
        credential,
        // Declares the SCP capabilities without carrying either leaf extension,
        // which is what makes the leaf non-conformant rather than malformed.
        scp_capabilities_with_keypackage_attestation(),
        Extensions::<LeafNode>::empty(),
        key_package_lifetime(clock),
    )?;

    Ok((bundle, signer, provider))
}

/// Mints an attested `KeyPackage` in one call, signing the attestation with a
/// caller-supplied Ed25519 key.
///
/// This exists so a test can produce a real, fully-attested `KeyPackage`
/// without a custody backend. It is compiled out of shipped artifacts, and it
/// is not a stand-in for the production signer: production reaches the identity
/// key through `KeyCustody::sign`, and the two-call
/// [`prepare_key_package`]/[`finish_key_package`] pair is the only route it
/// takes.
///
/// # Errors
///
/// Returns whatever [`prepare_key_package`] or [`finish_key_package`] returns.
#[cfg(any(test, feature = "testing"))]
pub fn mint_key_package_for_testing(
    credential: &ScpCredential,
    wrapping_pubkey: &[u8; PUBLIC_KEY_SIZE],
    clock: &dyn Clock,
    attestation_signing_key: &ed25519_dalek::SigningKey,
) -> Result<(KeyPackageBundle, SignatureKeyPair, InMemoryMlsProvider), MlsError> {
    use ed25519_dalek::Signer as _;

    let prepared = prepare_key_package(credential, wrapping_pubkey, clock)?;
    let signature = attestation_signing_key
        .sign(&prepared.attestation_signing_hash())
        .to_bytes();
    finish_key_package(prepared, signature)
}

