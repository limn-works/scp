/// Generates the leaf key material for a context-joinable `KeyPackage` and
/// returns the unsigned attestation over it (§9.7.1 leaf-creation site 2).
///
/// The leaf declares support for all three SCP `LeafNode` extension types
/// (`0xFF01` `scp_wrapping_key`, `0xFF02` `scp_context_params`, `0xFF03`
/// `scp_keypackage_attestation`), which RFC 9420 §12.1.8.2 (`valn0502`)
/// requires of any leaf added to an SCP context group, and carries the
/// `0xFF01` wrapping-key extension.
///
/// `wrapping_pubkey` is required rather than optional: §9.5.2 field 5 binds the
/// `0xFF01` value, and §9.7.1 check 6 compares the attestation against it, so a
/// leaf with no wrapping key cannot carry a verifiable attestation.
///
/// # Errors
///
/// Returns [`MlsError::CredentialSerializationFailed`] if `credential` cannot
/// be serialized, and [`MlsError::KeyPackageGenerationFailed`] if the leaf
/// signature keypair or the probe `KeyPackage` cannot be built.
pub fn prepare_key_package(
    credential: &ScpCredential,
    wrapping_pubkey: &[u8; PUBLIC_KEY_SIZE],
    clock: &dyn Clock,
) -> Result<PreparedKeyPackage, MlsError> {
    let signer = SignatureKeyPair::new(SCP_CIPHERSUITE.signature_algorithm())
        .map_err(|e| MlsError::KeyPackageGenerationFailed(format!("signer generation: {e}")))?;

    let lifetime = key_package_lifetime(clock);
    let capabilities = scp_capabilities_with_keypackage_attestation();
    let leaf_extensions = wrapping_key_extensions(wrapping_pubkey)?;

    // The probe build exists only to learn the two HPKE public keys openmls
    // generates. Its provider is dropped at the end of this function, so the
    // private halves it wrote never leave here; `finish_key_package` recreates
    // both keys in the provider it returns.
    let probe_provider = InMemoryMlsProvider::default();
    let transcript = TranscriptProvider::recording(&probe_provider);
    let probe = build_key_package(
        &transcript,
        &signer,
        credential,
        capabilities,
        leaf_extensions,
        lifetime,
    )?;

    let leaf_encryption_key = leaf_encryption_key_bytes(probe.key_package().leaf_node())?;
    let init_key = fixed_32(
        probe.key_package().hpke_init_key().as_slice(),
        "KeyPackage init_key",
    )?;
    let leaf_signature_key = fixed_32(signer.public(), "leaf signature_key")?;

    let attestation = KeyPackageAttestation {
        did: credential.did.clone(),
        leaf_signature_key,
        leaf_encryption_key,
        init_key,
        wrapping_key: *wrapping_pubkey,
        signing_key_id: credential.signing_key_id,
        // §9.7.1 check 11: the attestation's window is exactly the leaf's own
        // `Lifetime`, never a wider self-asserted one.
        issued_at: lifetime.not_before(),
        expires_at: lifetime.not_after(),
        signature: [0u8; SIGNATURE_SIZE],
    };

    Ok(PreparedKeyPackage {
        credential: credential.clone(),
        signer,
        wrapping_pubkey: *wrapping_pubkey,
        lifetime,
        recorded_draws: transcript.into_recorded(),
        attestation,
    })
}

/// Builds the finished `KeyPackage`, whose leaf carries the signed `0xFF03`
/// `scp_keypackage_attestation` extension.
///
/// `attestation_signature` is the Ed25519 signature the identity's
/// `#active`/`#agent` key produced over
/// [`PreparedKeyPackage::attestation_signing_hash`].
///
/// Returns the same triple the join path consumes: the `KeyPackageBundle` whose
/// public half is published, the leaf signature keypair, and the provider
/// holding the leaf's private HPKE keys.
///
/// # Errors
///
/// Returns [`MlsError::CredentialSerializationFailed`] if the credential cannot
/// be serialized, [`MlsError::StorageError`] if the leaf signature keypair
/// cannot be stored, [`MlsError::KeyPackageGenerationFailed`] if the build
/// fails, and [`MlsError::AttestationBindingMismatch`] if any of the four keys
/// the finished leaf carries differs from the key the attestation binds.
pub fn finish_key_package(
    prepared: PreparedKeyPackage,
    attestation_signature: [u8; SIGNATURE_SIZE],
) -> Result<(KeyPackageBundle, SignatureKeyPair, InMemoryMlsProvider), MlsError> {
    let PreparedKeyPackage {
        credential,
        signer,
        wrapping_pubkey,
        lifetime,
        recorded_draws,
        mut attestation,
    } = prepared;

    attestation.signature = attestation_signature;

    let provider = InMemoryMlsProvider::default();
    signer
        .store(provider.storage())
        .map_err(|e| MlsError::StorageError(format!("storing signature key: {e}")))?;

    let leaf_extensions = Extensions::<LeafNode>::from_vec(vec![
        make_wrapping_key_extension(&wrapping_pubkey),
        attestation.make_attestation_extension(),
    ])
    .map_err(|e| MlsError::ExtensionError(format!("attested leaf extension list: {e}")))?;

    let transcript = TranscriptProvider::replaying(&provider, recorded_draws);
    let bundle = build_key_package(
        &transcript,
        &signer,
        &credential,
        scp_capabilities_with_keypackage_attestation(),
        leaf_extensions,
        lifetime,
    )?;

    assert_attestation_binds_leaf(&attestation, &bundle)?;

    Ok((bundle, signer, provider))
}

/// Rejects a finished `KeyPackage` whose leaf does not carry exactly the four
/// public keys its attestation binds (§9.5.2 fields 2–5).
///
/// The replayed build is expected to reproduce the probe build's `init_key` and
/// `encryption_key`, because `openmls` derives both from drawn keying material
/// through `OpenMlsCrypto::derive_hpke_keypair`. This function is what makes
/// that expectation load-bearing nowhere: a `KeyPackage` that fails it is
/// discarded rather than published.
fn assert_attestation_binds_leaf(
    attestation: &KeyPackageAttestation,
    bundle: &KeyPackageBundle,
) -> Result<(), MlsError> {
    let leaf = bundle.key_package().leaf_node();

    let actual_signature_key = fixed_32(leaf.signature_key().as_slice(), "leaf signature_key")?;
    if actual_signature_key != attestation.leaf_signature_key {
        return Err(MlsError::AttestationBindingMismatch(
            "leaf signature_key differs from the attested value".to_owned(),
        ));
    }

    let actual_encryption_key = leaf_encryption_key_bytes(leaf)?;
    if actual_encryption_key != attestation.leaf_encryption_key {
        return Err(MlsError::AttestationBindingMismatch(
            "leaf encryption_key differs from the attested value".to_owned(),
        ));
    }

    let actual_init_key = fixed_32(
        bundle.key_package().hpke_init_key().as_slice(),
        "KeyPackage init_key",
    )?;
    if actual_init_key != attestation.init_key {
        return Err(MlsError::AttestationBindingMismatch(
            "KeyPackage init_key differs from the attested value".to_owned(),
        ));
    }

    // RFC 9420 §10.1 and §9.7.1 check 8: a KeyPackage's two HPKE keys are
    // distinct. Rejecting a degenerate pair here means SCP never publishes one.
    if actual_init_key == actual_encryption_key {
        return Err(MlsError::AttestationBindingMismatch(
            "KeyPackage init_key equals its LeafNode encryption_key (RFC 9420 §10.1)".to_owned(),
        ));
    }

    let actual_wrapping_key = crate::wrapping_extension::extract_wrapping_key(leaf.extensions())?
        .ok_or_else(|| {
        MlsError::AttestationBindingMismatch(
            "leaf carries no scp_wrapping_key (0xFF01) extension".to_owned(),
        )
    })?;
    if actual_wrapping_key != attestation.wrapping_key {
        return Err(MlsError::AttestationBindingMismatch(
            "leaf scp_wrapping_key differs from the attested value".to_owned(),
        ));
    }

    Ok(())
}

/// Builds one `KeyPackage` under [`SCP_CIPHERSUITE`] with the given leaf
/// capabilities, leaf extensions, and `Lifetime`.
///
/// The `Lifetime` comes from the injected [`Clock`] (ADR-057 §Prereq-1), never
/// from openmls's internal clock — under the wasm `js` feature that internal
/// clock reads an attacker-overridable `Date.now()`.
fn build_key_package<P: OpenMlsProvider>(
    provider: &P,
    signer: &SignatureKeyPair,
    credential: &ScpCredential,
    capabilities: Capabilities,
    leaf_extensions: Extensions<LeafNode>,
    lifetime: Lifetime,
) -> Result<KeyPackageBundle, MlsError> {
    let credential_with_key = CredentialWithKey {
        credential: BasicCredential::new(credential.to_bytes()?).into(),
        signature_key: signer.to_public_vec().into(),
    };

    KeyPackage::builder()
        .leaf_node_capabilities(capabilities)
        .leaf_node_extensions(leaf_extensions)
        .key_package_lifetime(lifetime)
        .build(SCP_CIPHERSUITE, provider, signer, credential_with_key)
        .map_err(|e| MlsError::KeyPackageGenerationFailed(e.to_string()))
}

/// Builds the single-entry leaf extension list carrying the `0xFF01`
/// wrapping-key extension, which the probe build uses.
fn wrapping_key_extensions(
    wrapping_pubkey: &[u8; PUBLIC_KEY_SIZE],
) -> Result<Extensions<LeafNode>, MlsError> {
    Extensions::<LeafNode>::single(make_wrapping_key_extension(wrapping_pubkey))
        .map_err(|e| MlsError::ExtensionError(format!("wrapping key extension: {e}")))
}

