//! Attested `KeyPackage` minting — the signer side of the `0xFF03`
//! `scp_keypackage_attestation` `LeafNode` extension (§9.7.1, §9.5.2;
//! ADR-057 Amendment 2026-08-01).
//!
//! [`keypackage_attestation`](crate::keypackage_attestation) defines the
//! attestation type and its verifier. This module produces one: it generates a
//! `KeyPackage` whose leaf carries an `#active`/`#agent`-signed attestation
//! binding all four of that leaf's public keys to the member's DID.
//!
//! # Why minting takes two calls
//!
//! §9.5.2 binds four keys: the leaf `signature_key`, the `LeafNode`
//! ratchet-tree `encryption_key`, the `KeyPackage` `init_key`, and the
//! `scp_wrapping_key` (`0xFF01`) `wrapping_key`. The attestation over those
//! four rides **inside** the leaf, so the leaf's own self-signature covers it.
//! Two of the four keys — `encryption_key` and `init_key` — are generated by
//! `openmls` inside `KeyPackage::builder().build()`, and `openmls` 0.8.1
//! exposes no public seam that accepts pre-chosen values for them
//! (`KeyPackage::create` and `LeafNode::new_with_key` are both private, and
//! `KeyPackageBundle::new` is `test-utils`-gated). A single call therefore
//! cannot both learn those keys and sign over them.
//!
//! [`prepare_key_package`] resolves that by building a **probe** `KeyPackage`
//! while recording every random draw `openmls` makes, reading the two generated
//! keys off the probe, and returning the unsigned attestation. The caller signs
//! [`PreparedKeyPackage::attestation_signing_hash`] with the identity's
//! `#active`/`#agent` custody key — an operation this crate never performs,
//! because `scp-mls` is wasm-safe and `KeyCustody` lives in the native-only
//! `scp-platform`. [`finish_key_package`] then replays the recorded draw
//! sequence into a second build, which reproduces the same two keys (openmls
//! derives both with `OpenMlsCrypto::derive_hpke_keypair`, a pure function of
//! its input keying material) and adds the signed `0xFF03` extension to the
//! leaf.
//!
//! # The replay is checked, never trusted
//!
//! [`finish_key_package`] compares the finished `KeyPackage`'s actual
//! `init_key`, `encryption_key`, `signature_key`, and `0xFF01` wrapping key
//! against the four values the attestation binds, and returns
//! [`MlsError::AttestationBindingMismatch`] on any difference. A future
//! `openmls` release that draws randomness differently therefore makes minting
//! **fail**, and can never make it emit a `KeyPackage` whose attestation binds
//! keys the leaf does not carry.
//!
//! # No unattested production path
//!
//! This module is the only production route to a `KeyPackage` in `scp-mls`.
//! [`finish_key_package`] takes the 64-byte signature by value, so a
//! `KeyPackage` with no attestation is unrepresentable here rather than merely
//! discouraged. A caller that holds no custody key returns
//! [`MlsError::AttestationSignerUnavailable`] instead of minting an unattested
//! `KeyPackage`.
//!
//! See spec §9.7.1 ("`KeyPackage` leaf key and DID attestation"), §9.5.2
//! (`KeyPackageAttestation`), and §9.18.7 (`0xFF03`).

