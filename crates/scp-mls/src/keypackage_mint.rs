/// A `KeyPackage` whose four attested public keys are fixed and whose
/// attestation is not yet signed.
///
/// [`prepare_key_package`] produces one; [`finish_key_package`] consumes it.
/// Between the two calls the caller signs
/// [`attestation_signing_hash`](Self::attestation_signing_hash) with the DID's
/// `#active`/`#agent` key.
pub struct PreparedKeyPackage {
    /// The credential the finished leaf embeds.
    credential: ScpCredential,
    /// The ephemeral, context-scoped MLS leaf signature keypair (§9.7.1). The
    /// finished `KeyPackage` self-signs its leaf with this key, and the caller
    /// retains it to join the group the leaf is added to.
    signer: SignatureKeyPair,
    /// The member's 32-byte X25519 `scp_wrapping_key` (`0xFF01`) public key.
    wrapping_pubkey: [u8; PUBLIC_KEY_SIZE],
    /// The `Lifetime` both builds stamp, and the window the attestation's
    /// `issued_at`/`expires_at` reproduce (§9.7.1 check 11).
    lifetime: Lifetime,
    /// Every random draw the probe build made, replayed by the second build.
    recorded_draws: Vec<Vec<u8>>,
    /// The attestation over the probe build's four public keys, with an
    /// all-zero signature until [`finish_key_package`] installs the real one.
    attestation: KeyPackageAttestation,
}

impl std::fmt::Debug for PreparedKeyPackage {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // The leaf signature keypair and the recorded draws are private key
        // material, so this prints neither.
        f.debug_struct("PreparedKeyPackage")
            .field("did", &self.credential.did)
            .field("signing_key_id", &self.credential.signing_key_id)
            .field("issued_at", &self.attestation.issued_at)
            .field("expires_at", &self.attestation.expires_at)
            .field("signer", &"<redacted>")
            .field("recorded_draws", &"<redacted>")
            .finish_non_exhaustive()
    }
}

impl PreparedKeyPackage {
    /// Returns the 32-byte SHA-256 hash the identity's `#active`/`#agent` key
    /// signs (§9.5.1).
    ///
    /// The signer computes an Ed25519 signature over **these 32 bytes** and
    /// over nothing else — not over the canonical preimage, and not over the
    /// `0xFF03` extension body (§9.5.2).
    #[must_use]
    pub fn attestation_signing_hash(&self) -> [u8; 32] {
        self.attestation.signing_hash()
    }

    /// Returns the unsigned attestation, so a caller can read the four keys
    /// and the validity window it binds.
    #[must_use]
    pub const fn attestation(&self) -> &KeyPackageAttestation {
        &self.attestation
    }
}

